class TransectAlgorithm(QgsProcessingAlgorithm):
    post_processors = {}
    OUTPUT = 'OUTPUT'
    DEM = 'DEM'
    INPUT = 'INPUT'
    elev_field = 'elev_field'
    nesting_field = 'nesting_field'
    id_field = 'id_field'
    writeLog = 'writeLog'

    def __init__(self):
        super().__init__()
        self.logger = None
        self.feedback = None
        self.context = None
        self.t0 = None
        self.logger = None
        self.write_log = None

    def initAlgorithm(self, config):
        self.addParameter(
            QgsProcessingParameterFeatureSource(
                self.INPUT,
                self.tr('Input polygons'),
                [QgsProcessing.TypeVectorPolygon],
                optional=False,
            )
        )
        self.addParameter(
            QgsProcessingParameterField(
                self.id_field,
                self.tr('Unique ID field'),
                parentLayerParameterName=self.INPUT,
                allowMultiple=False,
                optional=False,
                defaultValue='ID',
            )
        )
        self.addParameter(
            QgsProcessingParameterField(
                self.nesting_field,
                self.tr('Nesting field'),
                parentLayerParameterName=self.INPUT,
                allowMultiple=False,
                optional=False,
                defaultValue='Nesting',
            )
        )

        #self.addParameter(
        #    QgsProcessingParameterRasterLayer(
        #        self.DEM,
        #        self.tr('Input DEM'),
        #        optional=False
        #    )
        #)

        self.addParameter(
            QgsProcessingParameterVectorDestination(
            self.OUTPUT,
            self.tr('Transect GPKG'),
            optional=False)
        )

        self.addParameter(
            QgsProcessingParameterBoolean(
                self.writeLog,
                'Write log file',
                True,
                optional=True)
        )

    def update_log(self, message):
        t1 = datetime.now()
        if not message.startswith('..'):  # don't publish tracker updates to GUI
            self.feedback.pushInfo('{}'.format(str(t1 - self.t0)[:-4]) + ' ' + message + '\n')
        if self.write_log:
            if message.startswith('..'):
                self.logger.info(message)
            else:
                self.logger.info('{}'.format(str(t1 - self.t0)[:-4]) + ' ' + message)

    def processAlgorithm(self, parameters, context, feedback):
        self.context = context
        self.feedback = feedback
        self.t0 = datetime.now()
        self.od = self.parameterAsVectorLayer(parameters, self.INPUT, context)
        self.id_field = self.parameterAsString(parameters, self.id_field, context)
        self.nesting_field = self.parameterAsString(parameters, self.nesting_field, context)
        #self.dem = self.parameterAsRasterLayer(parameters, self.DEM, context)
        #uri_components = QgsProviderRegistry.instance().decodeUri(self.dem.dataProvider().name(), self.dem.publicSource())
        uri_components_od = QgsProviderRegistry.instance().decodeUri(self.od.dataProvider().name(), self.od.publicSource())
        self.out_path = self.parameterAsOutputLayer(parameters, self.OUTPUT, context)
        self.write_log = self.parameterAsInt(parameters, self.writeLog, context)
        self.logger = logging.getLogger(__name__)
        self.update_log('Script started at ' + self.t0.strftime('%Y-%m-%d %H:%M:%S') + '\n')
        self.update_log('\nInput polygons: ' + uri_components_od['path'] +
                        #'\nInput DEM: ' + uri_components['path'] +
                        '\nOutput GPKG: ' + self.out_path)

        if os.path.exists(self.out_path):
            os.remove(self.out_path)

        if self.write_log:
            console_handler = logging.StreamHandler()
            log_filename = os.path.splitext(self.out_path)[0] + '_' + self.t0.strftime('%Y%m%d_%H%M%S') + '_log.txt'
            if os.path.exists(log_filename):
                os.remove(log_filename)
            file_handler = logging.FileHandler(log_filename, mode="a", encoding="utf-8")
            self.logger.addHandler(console_handler)
            self.logger.addHandler(file_handler)
            self.logger.setLevel("INFO")
            self.update_log('Logging to: ' + log_filename + '\n')

        idx = self.od.fields().indexFromName(self.id_field)
        QgsProject.instance().addMapLayer(self.od, False)
        self.od.selectByExpression('"' + self.nesting_field + '" = 1')
        unique_ids = []
        for f in self.od.selectedFeatures():
            unique_ids.append(f[idx])

        self.update_log('Creating transect lines...')

        #v_lines = QgsVectorLayer("multilinestring", "temp", 'memory')
        #v_lines.dataProvider().addAttributes([QgsField("id", QMetaType.Type.Int)])
        #v_lines.updateFields()

        milestones = list(range(5, 101, 5))
        self.update_log('\n{}% complete @ '.format('0') + datetime.now().strftime("%H:%M.%S"))
        #fields = v_lines.fields()

        dissolved_list = []
        for i, id in enumerate(unique_ids):
            self.od.selectByExpression('"' + self.id_field + '" = ' + str(id))

            voronoi = processing.run("grass:v.voronoi.skeleton", {
                'input':QgsProcessingFeatureSourceDefinition(self.od.id(), selectedFeaturesOnly=True, featureLimit=-1,
                                                             geometryCheck=QgsFeatureRequest.GeometryAbortOnInvalid),
                'smoothness':0.25,'thin':-1,'-a':False,'-s':True,'-l':False,'-t':True,
                'output':'TEMPORARY_OUTPUT',
                'GRASS_REGION_PARAMETER':None,'GRASS_SNAP_TOLERANCE_PARAMETER':-1,'GRASS_MIN_AREA_PARAMETER':0.0001,
                'GRASS_OUTPUT_TYPE_PARAMETER':0,'GRASS_VECTOR_DSCO':'','GRASS_VECTOR_LCO':'',
                'GRASS_VECTOR_EXPORT_NOCAT':False})

            voronoid = voronoi['output']


            dissolve = processing.run("native:dissolve", {'INPUT': voronoid,
                'FIELD': [], 'SEPARATE_DISJOINT': True, 'OUTPUT': 'TEMPORARY_OUTPUT'})

            dissolved = dissolve['OUTPUT']

            single = processing.run("native:multiparttosingleparts", {
                'INPUT': dissolved,
                'OUTPUT': 'TEMPORARY_OUTPUT'})

            singled = single['OUTPUT']
            singled.dataProvider().addAttributes([QgsField("poly_id", QMetaType.Type.Int)])
            singled.updateFields()
            poly_idx = singled.fields().indexOf('poly_id')
            context = QgsExpressionContext()
            context.appendScopes(QgsExpressionContextUtils.globalProjectLayerScopes(singled))

            with edit(singled):
                for f in singled.getFeatures():
                    context.setFeature(f)
                    singled.changeAttributeValue(f.id(), poly_idx, id)

            dissolved_list.append(singled)
            #
            # self.update_log('Count: ' + str(dissolved.featureCount()))
            #
            # features = []
            #
            # for feature in dissolved.getFeatures():
            #     temp_feature = QgsFeature()
            #     temp_feature.setFields(fields)
            #     temp_feature['id'] = i
            #     temp_feature.setGeometry(feature.geometry())
            #     features.append(temp_feature)
            #
            # v_lines.dataProvider().addFeatures(features)
            # self.update_log('V_Count: ' + str(v_lines.featureCount()))

            percentage_complete = (100.0 * (i + 1) / len(unique_ids))
            while len(milestones) > 0 and percentage_complete >= milestones[0]:
                self.update_log('\n{}% complete @ '.format(milestones[0]) + ' ' + datetime.now().strftime("%H:%M.%S"))
                # remove that milestone from the list
                milestones = milestones[1:]
            feedback.setProgress(percentage_complete)
            if feedback.isCanceled():
                return {}

        merge = processing.run("native:mergevectorlayers", {'LAYERS': dissolved_list,
                                                    'CRS': None, 'OUTPUT': 'TEMPORARY_OUTPUT'})
        #self.update_log('Total_V_Count: ' + str(v_lines.featureCount()))
        merged = merge['OUTPUT']

        fields_to_keep = ['poly_id']
        fields_to_remove = [field.name() for field in merged.fields() if field.name() not in fields_to_keep]

        merged.startEditing()
        for field_name in fields_to_remove:
            merged.deleteAttribute(merged.fields().indexOf(field_name))
        merged.commitChanges()

        fid = processing.run("native:addautoincrementalfield", {
            'INPUT': merged,
            'FIELD_NAME': 'fid', 'START': 0, 'MODULUS': 0, 'GROUP_FIELDS': [], 'SORT_EXPRESSION': '',
            'SORT_ASCENDING': True, 'SORT_NULLS_FIRST': False, 'OUTPUT': 'TEMPORARY_OUTPUT'})

        fided = fid['OUTPUT']
        QgsProject.instance().addMapLayer(fided)
        points = processing.run("native:pointsalonglines", {
            'INPUT': fided, 'DISTANCE': 150, 'START_OFFSET': 0, 'END_OFFSET': 0, 'OUTPUT': self.out_path})
        pointed = points['OUTPUT']

        #if os.path.exists(self.out_path):
        #    os.remove(self.out_path)
        #params = {'INPUT': pointed,
        #          'LAYER_NAME': 'Transects',
        #          'OUTPUT': self.out_path}
        #processing.run("native:savefeatures", params, is_child_algorithm=True, context=self.context, feedback=self.feedback)

        self.update_log('Exported transects to ' + self.out_path)

        self.update_log('Script finished at ' + datetime.now().strftime('%Y-%m-%d %H:%M:%S') + '\n')

        return {}

    def postProcessAlgorithm(self, context, feedback):

        return {self.OUTPUT: self.out_path}

    def name(self):
        """
        Returns the algorithm name, used for identifying the algorithm. This
        string should be fixed for the algorithm, and must not be localised.
        The name should be unique within each provider. Names should contain
        lowercase alphanumeric characters only and no spaces or other
        formatting characters.
        """
        return 'Create basin transects'

    def displayName(self):
        """
        Returns the translated algorithm name, which should be used for any
        user-visible display of the algorithm name.
        """
        return self.tr(self.name())

    def tr(self, string):
        return QCoreApplication.translate('Processing', string)

    def shortHelpString(self):
        file = os.path.dirname(__file__) + '/doc/classify.help'
        if not os.path.exists(file):
            return ''
        with open(file) as helpf:
            help = helpf.read()
        return help

    def flags(self):
        """
        Algorithm manipulating project (toggle layer) or using external library are not thread safe
        See :https://api.qgis.org/api/classQgsProcessingAlgorithm.html#a6a8c21fab75e03f50f45e41a9d67dbc3a229dea6cedf8c59132196dee09d4f2f6
        """
        return super().flags() | QgsProcessingAlgorithm.FlagNoThreading

    def createInstance(self):
        return TransectAlgorithm()
