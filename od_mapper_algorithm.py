    def _as_vector_layer(self, output):
        """
        Resolve a Processing output into a QgsVectorLayer.

        Processing algorithms may return either a layer object or a temporary
        output/source string, depending on QGIS version and provider.
        """
        if isinstance(output, QgsVectorLayer):
            return output

        layer = QgsProcessingUtils.mapLayerFromString(output, self.context)

        if layer is None:
            raise QgsProcessingException(
                f'Could not resolve Processing output layer: {output}'
            )

        if not isinstance(layer, QgsVectorLayer):
            raise QgsProcessingException(
                f'Processing output is not a vector layer: {output}'
            )

        return layer

    def check_lip(self, f, last_f):
        if f is None:
            return

        feature_id = f['ID']
        if feature_id  in self.lip_blacklist:
            self.update_log('...Lip already blacklisted')
        elif self.allow_peaks == 0 and f['diff_maxElev'] > self.cInterval:
            self.update_log('...Lip skipped - no peaks allowed')
            self.lip_blacklist.add(feature_id)

        elif (
            self.allow_peaks == 1
            and last_f is not None
            and f['diff_maxElev'] > 0
            and (f['diff_maxElev'] - last_f['diff_maxElev']) > 100
        ):
            self.update_log('...Lip skipped - diff>100')
            self.lip_blacklist.add(feature_id)

        elif (
            f['Extent'] is not None
            and f['Depth'] is not None
            and f['Extent'] >= self.minODarea
            and f['Depth'] >= self.minODdepth - self.DEPTH_EPSILON
        ):
            self.update_log(f'...Lip {feature_id} ok and marked')
            self.tracked_lips.append(feature_id)

        else:
            self.update_log('...Lip skipped - not ok')
            self.lip_blacklist.add(feature_id)

    def tracker(self, intersected_layer, start_z):
        if intersected_layer is None or not intersected_layer.isValid():
            raise QgsProcessingException(
                'Tracker received an invalid intersected contour layer.'
            )

        required_fields = {
            'ID', 'ELEV', 'Boundary', 'Extent',
            'Depth', 'Seeds', 'diff_maxElev',
        }

        available_fields = {field.name() for field in intersected_layer.fields()}
        missing_fields = required_fields - available_fields

        if missing_fields:
            raise QgsProcessingException(
                'Tracker input is missing required fields: '
                + ', '.join(sorted(missing_fields))
            )
        
        request = QgsFeatureRequest()
        request.setOrderBy(
            QgsFeatureRequest.OrderBy([
                QgsFeatureRequest.OrderByClause('Depth', ascending=True)
            ])
        )
        request.setFlags(QgsFeatureRequest.Flag.NoGeometry)
        request.setSubsetOfAttributes(
            list(required_fields),
            intersected_layer.fields(),
        )

        cont = set()  # contours which have already crossed
        self.tracked_lips = []
        seeds = 1
        last_elev = -9999  # needed if only 1 intersect on first transect line in file
        counter = 0
        max_count = intersected_layer.featureCount()
        error = 0
        last_f_2 = None
        last_f = None
        check_f = None
        last_contour = 1    

        

        for f in intersected_layer.getFeatures(request):
            if self.feedback.isCanceled():
                return []

            counter += 1

            self.update_log(
                f'..TRACKER_ENTER {counter}/{max_count}: '
                f'FID={f.id()}'
            )
            
            feature_id = f['ID']
            elev = f['ELEV']
            seeds_value = f['Seeds']
            boundary = f['Boundary']

            if feature_id is None or elev is None or seeds_value is None:
                self.update_log(
                    f'...Skipping invalid feature: '
                    f'ID={feature_id}, ELEV={elev}, Seeds={seeds_value}'
                )
            
            if start_z > f['ELEV']:
                self.update_log(f"...{f['ID']}, {start_z}>{f['ELEV']}, Minima above contour")
                error += 1
            elif f['ID'] in cont:
                self.update_log(f"...{counter}/{max_count}, {f['ID']}, Recrossing contour")
            else:
                if boundary is None or last_contour is None or last_contour <= 0:
                    self.update_log(
                        f'...Skipping ID={f["ID"]}: invalid boundary values '
                        f'(Boundary={boundary}, previous={last_contour})'
                    )
                    continue
                diff = (f['Boundary'] / last_contour) * 100  # percentage increase from last contour

                #if f['Seeds'] == 0:
                #    self.update_log(f"...{f['ID']}, {diff:.1f}/{self.contour_change}, Entering a contour without seeds")
                #    error += 1  # entering a contour without seeds
                if counter > 1 and (f['ELEV'] - last_elev) != self.cInterval:  # perimeters can be longer on lower elevations!
                    self.update_log(f"...{f['ID']}, {diff:.1f}/{self.contour_change}, Left basin")
                    error += 1  # left basin into another OD (contour getting smaller/diff)
                elif f['ELEV'] < int(last_elev):
                    self.update_log(f"...{f['ID']}, {diff:.1f}/{self.contour_change}, Going downhill")
                    error += 1  # going downhill
                elif diff > self.flatbottom and counter == 2:  # on the second contour
                    self.update_log(f"...{counter}/{max_count}, {f['ID']}, {diff:.1f}/{self.flatbottom}, Too big second jump")
                    error += 1  # initial contour change too large

                elif diff > self.contour_change and counter > 2:  # above the second contour
                    self.update_log(f"...{counter}/{max_count}{f['ID']}, {diff:.1f}/{self.contour_change}, Too big a jump")
                    error += 1  # contour change too large

                elif f['Seeds'] > seeds and seeds <= 2:
                    if counter == 2:
                        self.update_log(f"...{counter}/{max_count}, {f['ID']}, {diff:.1f}/{self.flatbottom}, Seeds increased")
                        self.update_log(f"...Checking lip {check_f['ID']}")
                    else:
                        self.update_log(f"...{counter}/{max_count}, {f['ID']}, {diff:.1f}/{self.contour_change}, Seeds increased")
                    self.update_log(f"...Checking lip {check_f['ID']}")
                    if last_f_2:
                        self.check_lip(check_f, last_f_2)
                    else:
                        self.check_lip(check_f,
                                       last_f)  # for when checking the first contour (diff_maxElev jump does not matter)
                    check_f = f
                    last_f_2 = last_f
                    last_f = f

                elif not self.allow_peaks and f['diff_maxElev'] > self.cInterval:  # don't track as potential lip, but continue up
                    self.update_log(f"...{counter}/{max_count}, {f['ID']}, Basin contains a peak {f['diff_maxElev']}m above the lip")
                elif self.allow_peaks and last_f:
                    if f['diff_maxElev'] > 0 and (f['diff_maxElev'] - last_f['diff_maxElev']) > 100:  # don't track as potential lip, but continue up
                        self.update_log(f"...{counter}/{max_count}, {f['ID']}, Basin contains a sudden peak {f['diff_maxElev']}m above the lip")
                        #error += 1  # contour change too large
                        self.update_log(f"...Checking lip {check_f['ID']}")
                        if last_f_2:
                            self.check_lip(check_f, last_f_2)
                        else:
                            self.check_lip(check_f, last_f)  # if on the second contour
                        last_f = f
                    else:
                        self.update_log(f"...{counter}/{max_count}, {f['ID']}, {diff:.1f}/{self.contour_change}, OK")
                        check_f = f
                        last_f_2 = last_f
                        last_f = f
                else:
                    self.update_log(f"...{counter}/{max_count}, {f['ID']}, {diff:.1f}/{self.contour_change}, OK")
                    check_f = f
                    last_f_2 = last_f
                    last_f = f


            if error > 0 or counter == max_count:
                if check_f:
                    self.update_log(f"...Checking lip {check_f['ID']}")
                    if last_f_2:
                        self.check_lip(check_f, last_f_2)
                    else:
                        self.check_lip(check_f, last_f) # if on the second contour
                    return self.tracked_lips

            cont.add(f['ID'])
            last_contour = f['Boundary']
            last_elev = f['ELEV']
            seeds = f['Seeds']

    def nesting(self, od_polygons_layer):
        field_idx = od_polygons_layer.fields().indexOf('Nesting')
        for i in range(1, 1000):
            if i == 1:
                od_polygons_layer.selectByExpression('(overlay_contains(@layer) is True and overlay_within(@layer) is False) or overlay_disjoint(@layer)')

            elif i > 1:
                od_polygons_layer.selectByExpression('overlay_within(@layer) and Nesting is NULL and overlay_within(@layer, filter:= Nesting is NULL) IS False')

            od_polygon_count = od_polygons_layer.selectedFeatureCount()
            if od_polygon_count == 0:
                break
            else:
                self.update_log(f'Nesting level {i}: n = {od_polygon_count}')
                context_exp = QgsExpressionContext()
                context_exp.appendScopes(QgsExpressionContextUtils.globalProjectLayerScopes(od_polygons_layer))

                with edit(od_polygons_layer):
                    for f in od_polygons_layer.getSelectedFeatures():
                        context_exp.setFeature(f)
                        od_polygons_layer.changeAttributeValue(f.id(), field_idx, i)

    def update_log(self, message):
        t1 = datetime.now()
        elapsed = str(t1 - self.t0)[:-4]
        if not message.startswith('..'):  # don't publish tracker updates to GUI
            self.feedback.pushInfo(f'{elapsed} {message}\n')
        if self.keep_log:
            if message.startswith('..'):
                self.logger.info(message)
            else:
                self.logger.info(f'{elapsed} {message}')

    def create_od_gpkg(self, layer, layer_name):
        if os.path.exists(self.ODfilename):
            os.remove(self.ODfilename)
        params = {'INPUT': layer,
                  'LAYER_NAME': layer_name,
                  'OUTPUT': self.ODfilename}
        processing.run("native:savefeatures", params, is_child_algorithm=True, context=self.context, feedback=self.feedback)
        self.update_log(f'Exported {layer_name} layer to {self.ODfilename}')
    
    def export_layer(self, layer, layer_name):
        params = {'INPUT': layer,
                  'OPTIONS': f'-overwrite -nln {layer_name}',
                  'OUTPUT': self.ODfilename}
        processing.run("gdal:convertformat", params, is_child_algorithm=True, context=self.context, feedback=self.feedback)
        self.update_log(f'Exported {layer_name} layer to {self.ODfilename}')

    def processAlgorithm(self, parameters, context, feedback):
        self.context = context
        self.feedback = feedback
        self.t0 = datetime.now()
        self.minODarea = self.parameterAsDouble(parameters, self.MIN_OD_AREA, context)
        self.minODdepth = self.parameterAsInt(parameters, self.MIN_OD_DEPTH, context)
        self.DEPTH_EPSILON = 1e-6
        self.maxODperim = self.parameterAsInt(parameters, self.MAX_OD_PERIM, context)
        self.cInterval = self.parameterAsInt(parameters, self.CONTOUR_INTERVAL, context)
        self.contour_change = self.parameterAsInt(parameters, self.CONTOUR_THRESHOLD, context)
        self.flatbottom = self.parameterAsInt(parameters, self.FLAT_BOTTOM, context)
        load_od = self.parameterAsBool(parameters, self.LOAD_OD, context)
        self.allow_peaks = self.parameterAsBool(parameters, self.PEAKS, context)
        self.keep_log = self.parameterAsBool(parameters, self.WRITE_LOG, context)
        self.lip_blacklist = set()  # lips which have failed criteria from other minima starting points

        dem = self.parameterAsRasterLayer(parameters, self.INPUT, context)
        crs = dem.crs()
        if not crs.isValid():
            raise QgsProcessingException(
                'The input DEM does not have a valid CRS.'
            )

        if crs.isGeographic():
            raise QgsProcessingException(
                'The input DEM must use a projected CRS with metre-based units; '
                f'{crs.authid()} uses geographic coordinates (degrees).'
            )

        if crs.mapUnits() != QgsUnitTypes.DistanceUnit.DistanceMeters:
            raise QgsProcessingException(
                'The input DEM must use metre-based map units. '
                f'CRS {crs.authid()} uses '
                f'{QgsUnitTypes.toString(crs.mapUnits())}.'
            )

        uri_components = QgsProviderRegistry.instance().decodeUri(dem.dataProvider().name(), dem.publicSource())
        self.ODfilename = self.parameterAsFile(parameters, self.OUTPUT, context)

        if self.MASK_FILE not in parameters or parameters[self.MASK_FILE] is None:
            mask = None
            mask_name = 'No mask used'
        else:
            mask = self.parameterAsVectorLayer(parameters, self.MASK_FILE, context)
            mask_name = mask.name()

        if self.CONTOURS_FILE not in parameters or parameters[self.CONTOURS_FILE] is None:
            old_contours = None
            contours_name = 'Empty'
        else:
            old_contours = self.parameterAsVectorLayer(parameters, self.CONTOURS_FILE, context)
            contours_name = old_contours.name()

        grid_res_x = dem.rasterUnitsPerPixelX()
        grid_res_y = dem.rasterUnitsPerPixelY()

        if self.keep_log:
            self.logger = logging.getLogger(f'{__name__}.ODmapper')
            console_handler = logging.StreamHandler()
            log_filename = f"{os.path.splitext(self.ODfilename)[0]}_{self.t0.strftime('%Y%m%d_%H%M%S')}_log.txt"
            if os.path.exists(log_filename):
                os.remove(log_filename)
            file_handler = logging.FileHandler(log_filename, mode="a", encoding="utf-8")
            self.logger.addHandler(console_handler)
            self.logger.addHandler(file_handler)
            self.logger.setLevel(logging.INFO)
            self.logger.propagate = False

            for handler in self.logger.handlers[:]:
                handler.close()
                self.logger.removeHandler(handler)

            file_handler = logging.FileHandler(log_filename, encoding='utf-8')
            file_handler.setFormatter(logging.Formatter('%(message)s'))
            self.logger.addHandler(file_handler)

            self.update_log(f"Script started at {self.t0.strftime('%Y-%m-%d %H:%M:%S')}\n")
            self.update_log(
                f"\nInput DEM: {uri_components['path']}\n"
                f'Grid resolution (X,Y): {grid_res_x}, {grid_res_y} m\n'
                f'Contour Interval: {self.cInterval} m\n'
                f'Contour Threshold: {self.contour_change} %\n'
                f'Minimum OD area: {self.minODarea} km2\n'
                f'Minimum OD depth: {self.minODdepth} m\n'
                f'Maximum basin perimeter: {self.maxODperim} m\n'
                f'Mask: {mask_name}\n'
                f'Predefined contours: {contours_name}\n'
                f'Output GPKG: {self.ODfilename}\n'
                f'Projection: {dem.crs().authid()}\n'
            )

        # create the countours
        self.update_log('..\n\n1. Preparing files for mapping ODs')

        if old_contours:
            #self.update_log('Backing up original contours')
            #old_contours.selectAll()
            orig_contour_layer = processing.run("native:saveselectedfeatures", {'INPUT': old_contours, 'OUTPUT': 'memory:'})['OUTPUT']
            #self.create_od_gpkg(orig_contour_layer, 'contours_original')
            #all_contours_layer = QgsVectorLayer(f'{old_contours}', 'Lines', 'ogr')
            self.update_log('Copying supplied contours')

            contour_copy = processing.run(
                "native:savefeatures",
                {
                    'INPUT': old_contours,
                    'OUTPUT': 'TEMPORARY_OUTPUT',
                },
                is_child_algorithm=True,
                context=context,
                feedback=feedback,
            )

            contour_layer = self._as_vector_layer(contour_copy['OUTPUT'])

        else:
            self.update_log('Creating contours')
            contouring = processing.run("gdal:contour", {'INPUT': dem, 'BAND': 1, 'INTERVAL': self.cInterval,
                                                         'FIELD_NAME': 'ELEV', 'CREATE_3D': False,
                                                         'IGNORE_NODATA': False, 'NODATA': None, 'OFFSET': 0,
                                                         'EXTRA': '', 'OUTPUT': 'TEMPORARY_OUTPUT'},
                                        is_child_algorithm=True, context=context)
            contour_layer = self._as_vector_layer(contouring['OUTPUT'])
            #self.create_od_gpkg(orig_contour_layer, 'contours_original')

        #all_contours_layer = QgsVectorLayer(f'{self.ODfilename}|layername=contours_original', 'Lines', 'ogr')
        #all_contours_layer.selectAll()
        #contour_layer = processing.run("native:saveselectedfeatures", 
        #                               {'INPUT': all_contours_layer, 'OUTPUT': 'memory:'},
        #                               context=context)['OUTPUT']
        #all_contours_layer.removeSelection()

        self.update_log(f'Found contours. n = {contour_layer.featureCount()}')

        processing.run("native:createspatialindex", {'INPUT': contour_layer}, is_child_algorithm=True, context=context)

        # Check for cancelation
        if feedback.isCanceled():
            return {}

        if mask:
            contour_layer.selectAll()
            processing.run("native:selectbylocation", {'INPUT': contour_layer, 'PREDICATE': [0, 6], 'INTERSECT': mask,
                                                       'METHOD': 3},
                           is_child_algorithm=True, context=context)

            if contour_layer.selectedFeatureCount() > 0:
                with edit(contour_layer):
                    contour_layer.deleteSelectedFeatures()
                num_of_features = contour_layer.featureCount()
                self.update_log(f'Removed contours beyond the mask. n = {num_of_features}')
            else:
                self.update_log('No contours lie beyond the mask.')

        # select remove open polylines by selecting where end and start points don't match
        contour_layer.selectByExpression('is_closed(@geometry) = FALSE')

        with edit(contour_layer):
            contour_layer.deleteSelectedFeatures()

        self.update_log(f'Removed open contours. n = {contour_layer.featureCount()}')

        if contour_layer.dataProvider().fieldNameIndex("Boundary") == -1:
            contour_layer.dataProvider().addAttributes([QgsField("Boundary", QMetaType.Type.Double, "double", 10, 3),
                                                        QgsField("Extent", QMetaType.Type.Double, "double", 10, 3)])
            contour_layer.updateFields()

        context_exp = QgsExpressionContext()
        context_exp.appendScopes(QgsExpressionContextUtils.globalProjectLayerScopes(contour_layer))

        with edit(contour_layer):
            field_idx = contour_layer.fields().indexOf('Boundary')
            attribute_changes = {}
            delete_ids = []
            for f in contour_layer.getFeatures():
                context_exp.setFeature(f)
                length = f.geometry().length()
                if length < (grid_res_x * 4) or length > self.maxODperim:# or length < self.minODperim:
                    delete_ids.append(f.id())
                else:
                    attribute_changes[f.id()] = {field_idx: length}
            contour_layer.dataProvider().changeAttributeValues(attribute_changes)
            contour_layer.deleteFeatures(delete_ids)

        # Check for cancelation
        if feedback.isCanceled():
            return {}

        self.update_log(
            f'Removed small ({grid_res_x * 4}m) and big ({self.maxODperim} m) contours. '
            f'n = {contour_layer.featureCount()}'
        )

        # Check for cancelation
        if feedback.isCanceled():
            return {}

        # reduce allContours layer to use only those that could contain seeds (reduces number of intersections needed)
        self.update_log('Polygonising contours')
        polygonise = processing.run("qgis:linestopolygons", {'INPUT': contour_layer, 'OUTPUT': 'TEMPORARY_OUTPUT'})
        line2polygon_layer = polygonise['OUTPUT']

        with edit(line2polygon_layer):
            field_idx = line2polygon_layer.fields().indexOf('Extent')
            for f in line2polygon_layer.getFeatures():
                context_exp.setFeature(f)
                area = f.geometry().area() * 1E-6
                # preconditions some small basins to large
                #if area < self.minODarea:
                #    line2polygon_layer.deleteFeature(f.id())
                #else:
                line2polygon_layer.changeAttributeValue(f.id(), field_idx, area)
        self.update_log(f'Removed small area contours. n = {line2polygon_layer.featureCount()}')

        processing.run("native:createspatialindex", {'INPUT': line2polygon_layer},
                       is_child_algorithm=True, context=context)

        # remove contours with peaks inside or where too small to be considered OD
        self.update_log('Calculating contour minimum/maximum elevation stats')

        zonal = processing.run(
            "native:zonalstatisticsfb",
            {
                'INPUT': line2polygon_layer,
                'INPUT_RASTER': dem,
                'RASTER_BAND': 1,
                'COLUMN_PREFIX': '_z_',
                'STATISTICS': [5, 6],  # minimum, maximum only
                'OUTPUT': 'TEMPORARY_OUTPUT',
            },
            is_child_algorithm=True,
            context=context
        )

        allcontour_polygons_layer = self._as_vector_layer(zonal['OUTPUT'])

        allcontour_polygons_layer.dataProvider().addAttributes([
            QgsField("diff_maxElev", QMetaType.Type.Double, "double", 10, 3),
            QgsField("Depth", QMetaType.Type.Double, "double", 10, 3),
        ])
        allcontour_polygons_layer.updateFields()

        max_diff_idx = allcontour_polygons_layer.fields().indexOf('diff_maxElev')
        depth_idx = allcontour_polygons_layer.fields().indexOf('Depth')

        request = QgsFeatureRequest()
        request.setFlags(QgsFeatureRequest.Flag.NoGeometry)
        request.setSubsetOfAttributes(
            ['_z_min', '_z_max', 'ELEV'],
            allcontour_polygons_layer.fields(),
        )

        attribute_changes = {}

        for feature in allcontour_polygons_layer.getFeatures(request):
            min_elev = feature['_z_min']
            max_elev = feature['_z_max']
            lip_elev = feature['ELEV']

            # Skip polygons with no raster data / only NoData.
            if min_elev is None or max_elev is None or lip_elev is None:
                continue

            attribute_changes[feature.id()] = {
                max_diff_idx: max_elev - lip_elev,
                depth_idx: lip_elev - min_elev,
            }

        if attribute_changes:
            with edit(allcontour_polygons_layer):
                allcontour_polygons_layer.dataProvider().changeAttributeValues(
                    attribute_changes
                )

        allcontour_polygons_layer.selectByExpression('"Depth" < 1')

        if allcontour_polygons_layer.selectedFeatureCount() > 0:
            with edit(allcontour_polygons_layer):
                allcontour_polygons_layer.deleteSelectedFeatures()

        self.update_log(
            f'Removed shallow basins. '
            f'n = {allcontour_polygons_layer.featureCount()}'
        )

        allcontour_polygons_layer.selectByExpression('"_z_min" > "ELEV"')

        if allcontour_polygons_layer.selectedFeatureCount() > 0:
            with edit(allcontour_polygons_layer):
                allcontour_polygons_layer.deleteSelectedFeatures()

        self.update_log('Calculating mean/median stats for remaining contours')

        zonal_shape = processing.run(
            "native:zonalstatisticsfb",
            {
                'INPUT': allcontour_polygons_layer,
                'INPUT_RASTER': dem,
                'RASTER_BAND': 1,
                'COLUMN_PREFIX': '_shape_',
                'STATISTICS': [2, 3],  # mean, median
                'OUTPUT': 'TEMPORARY_OUTPUT',
            },
            is_child_algorithm=True,
            context=context
        )

        allcontour_polygons_layer = self._as_vector_layer(zonal_shape['OUTPUT'])

        allcontour_polygons_layer.selectByExpression(
            '"_shape_median" > "ELEV" OR "_shape_mean" > "ELEV"'
        )

        if allcontour_polygons_layer.selectedFeatureCount() > 0:
            with edit(allcontour_polygons_layer):
                allcontour_polygons_layer.deleteSelectedFeatures()

        # delete lone polygons with a max elevation greater than the lip. The rest are dealt with in the tracker as some 'peaks' might be contained by higher lips.
        if not self.allow_peaks:
            allcontour_polygons_layer.selectByExpression(
                f'"diff_maxElev" > {self.cInterval} and overlay_disjoint(@layer)')

            if allcontour_polygons_layer.selectedFeatureCount() > 0:
                with edit(allcontour_polygons_layer):
                    allcontour_polygons_layer.deleteSelectedFeatures()
            self.update_log(f'Removed contours containing peaks. n = {allcontour_polygons_layer.featureCount()}')

        # create seeds
        processing.run("native:createspatialindex", {'INPUT': allcontour_polygons_layer}, is_child_algorithm=True, context=context)
        allcontour_polygons_layer.selectByExpression(
            f'NOT overlay_contains(@layer) '
            f'AND NOT ("Extent" < {self.minODarea} AND overlay_disjoint(@layer))'
        )


        self.update_log(f'Seed polygons. n = {allcontour_polygons_layer.selectedFeatureCount()}')

        contour_polygons_layer = processing.run("native:saveselectedfeatures",
                                                {'INPUT': allcontour_polygons_layer, 'OUTPUT': 'memory:'})['OUTPUT']
        
        self.create_od_gpkg(contour_polygons_layer, 'seed_polygons')

        # 1. Find the OD minima
        # -> Identify the elevation minimum within the polygon. Create points, attach elevation and
        # remove those that don't match minima

        self.update_log('..\n\n2. Seeding basins')
        self.update_log(f'Creating OD minima points from {contour_polygons_layer.featureCount()} seed polygons')

        dem2point = processing.run("native:generatepointspixelcentroidsinsidepolygons",
                                   {'INPUT_RASTER': dem, 'INPUT_VECTOR': contour_polygons_layer,
                                    'OUTPUT': 'TEMPORARY_OUTPUT'})
        minima_points_layer = dem2point['OUTPUT']

        #processing.run("native:createspatialindex", {'INPUT': minima_points_layer}, is_child_algorithm=True,context=context)
        self.update_log(f'Created minima points. n = {minima_points_layer.featureCount()}')

        self.update_log('Extracting elevation data to OD minima points')

        existing_field_names = set(f.name() for f in minima_points_layer.fields())
        sampling = processing.run("native:rastersampling",
                                  {'INPUT': minima_points_layer, 'RASTERCOPY': dem,
                                   'COLUMN_PREFIX': 'elevation_', 'OUTPUT': 'TEMPORARY_OUTPUT'},
                                  context=context)
        minima_points_layer = sampling['OUTPUT']
        # rastersampling names the new field itself, so find it by diffing against the pre-existing fields
        sampled_field_name = next(f.name() for f in minima_points_layer.fields() if f.name() not in existing_field_names)
        minima_points_layer.dataProvider().renameAttributes({minima_points_layer.fields().indexOf(sampled_field_name): 'elevation'})
        minima_points_layer.updateFields()

        # Find single minima by deleting all but the lowest point for each poly
        self.update_log('Finding individual OD minima')
        request = QgsFeatureRequest()
        clause1 = QgsFeatureRequest.OrderByClause('poly_id', ascending=True)
        clause2 = QgsFeatureRequest.OrderByClause('elevation', ascending=True)
        orderby = QgsFeatureRequest.OrderBy([clause1, clause2])
        request.setOrderBy(orderby).setFlags(QgsFeatureRequest.Flag.NoGeometry)

        if minima_points_layer.featureCount() > 0:
            delete_ids = []
            min_d = -9999
            min_id = -1
            for f in minima_points_layer.getFeatures(request):
                if f['elevation'] is None:
                    continue
                elif f['poly_id'] > min_id:
                    min_d = f['elevation']
                    min_id = f['poly_id']
                elif f['elevation'] >= min_d:
                    delete_ids.append(f.id())
            if delete_ids:
                minima_points_layer.dataProvider().deleteFeatures(delete_ids)

        # Remove minima that are above their seed polygon
        processing.run("native:createspatialindex", {'INPUT': minima_points_layer}, is_child_algorithm=True, context=context)
        join = processing.run("native:joinattributesbylocation", {'INPUT': minima_points_layer, 'PREDICATE': [0],
                                                                  'JOIN': contour_polygons_layer, 'JOIN_FIELDS': [],
                                                                  'METHOD': 0, 'DISCARD_NONMATCHING': False,
                                                                  'PREFIX': '',
                                                                  'OUTPUT': 'TEMPORARY_OUTPUT'},
                              context=context)
        joined_layer = join['OUTPUT']
        invalid_joined = processing.run(
            "native:extractbyexpression",
            {
                'INPUT': joined_layer,
                'EXPRESSION': '"elevation" > "ELEV"',
                'OUTPUT': 'TEMPORARY_OUTPUT',
            },
            is_child_algorithm=True,
            context=context
        )

        invalid_joined_layer = invalid_joined['OUTPUT']

        processing.run(
            "native:selectbylocation",
            {
                'INPUT': minima_points_layer,
                'PREDICATE': [0],
                'INTERSECT': invalid_joined_layer,
                'METHOD': 0,
            },
            is_child_algorithm=True,
            context=context
        )

        if minima_points_layer.selectedFeatureCount() > 0:
            with edit(minima_points_layer):
                minima_points_layer.deleteSelectedFeatures()

        num_of_features = minima_points_layer.featureCount()
        self.update_log(f'Reduced minima points. n = {num_of_features}')

        if num_of_features <= 0:
            return {}

        # Add field for checking if OD seeds start to be contained by the same contour. Need to use minima points
        self.update_log('Aggregating seed count within contour polygons.')

        allcontour_polygons_layer.removeSelection()
        contour_polygons_layer.removeSelection()
        processing.run("native:createspatialindex", {'INPUT': minima_points_layer}, is_child_algorithm=True, context=context)
        seeds = processing.run("native:countpointsinpolygon", {'POLYGONS': allcontour_polygons_layer,
                                                               'POINTS': minima_points_layer, 'WEIGHT': '',
                                                               'CLASSFIELD': '', 'FIELD': 'Seeds',
                                                               'OUTPUT': 'TEMPORARY_OUTPUT'}, context=context)
        seeds_layer = seeds['OUTPUT']
        processing.run("native:createspatialindex", {'INPUT': seeds_layer}, is_child_algorithm=True, context=context)

        within = processing.run("native:joinattributesbylocation", {'INPUT': seeds_layer, 'PREDICATE': [1],
                                                                    'JOIN': minima_points_layer,
                                                                    'JOIN_FIELDS': ['poly_id'], 'METHOD': 1,
                                                                    'DISCARD_NONMATCHING': True,
                                                                    'PREFIX': '', 'OUTPUT': 'TEMPORARY_OUTPUT'}, context=context)
        seeded_layer = within['OUTPUT']

        # remove contours that are not necessary
        seeded_layer.selectByExpression('Seeds = 0')
        self.update_log(f'Selecting unseeded . n = {seeded_layer.selectedFeatureCount()}')
        with edit(seeded_layer):
            seeded_layer.deleteSelectedFeatures()

        poly2line = processing.run("native:polygonstolines", {'INPUT': seeded_layer, 'OUTPUT': 'TEMPORARY_OUTPUT'}, context=context)
        contour_layer = poly2line['OUTPUT']

        with edit(contour_layer):
            my_field = contour_layer.fields().indexFromName('fid')
            contour_layer.dataProvider().deleteAttributes([my_field])
        contour_layer.updateFields()

        with edit(seeded_layer):
            my_field = seeded_layer.fields().indexFromName('fid')
            seeded_layer.dataProvider().deleteAttributes([my_field])
        seeded_layer.updateFields()

        # self.export_layer(contour_layer, 'tracking_contours')

        # 2. Setup contour tracking
        self.update_log('..\n\n3. Tracking')
        processing.run("native:createspatialindex", {'INPUT': seeded_layer}, is_child_algorithm=True, context=context)
        processing.run("native:createspatialindex", {'INPUT': minima_points_layer}, is_child_algorithm=True, context=context)

        context.temporaryLayerStore().addMapLayer(minima_points_layer)

        self.update_log(f'Iterating over minima points n={num_of_features}')

        depth_limit = self.minODdepth - self.DEPTH_EPSILON
        if self.allow_peaks:
            seeded_layer.selectByExpression(f'"Depth" >= {depth_limit} and Extent >= {self.minODarea} and overlay_disjoint(@layer)')
        else:
            seeded_layer.selectByExpression(
                f'"Depth" >= {depth_limit} and Extent >= {self.minODarea} and "diff_maxElev" <= {self.cInterval} and overlay_disjoint(@layer)'
            )

        # create a first list of basins with a single contour
        lips = []
        features = seeded_layer.selectedFeatures()
        for feat in features:
            lips.append(feat['ID'])

        if len(lips) == 1:
            seeded_layer.selectByExpression(f'"ID" = {lips[0]}')
        elif len(lips) > 1:
            seeded_layer.selectByExpression(f'ID in {tuple(lips)}')
        if seeded_layer.selectedFeatureCount() > 1:
            with edit(seeded_layer):
                seeded_layer.deleteSelectedFeatures()

        processing.run("native:selectbylocation", {'INPUT': minima_points_layer,
                                                   'PREDICATE': [6],
                                                   'INTERSECT': seeded_layer,
                                                   'METHOD': 0},
                       is_child_algorithm=True, context=context)

        minima_by_poly_id = {}

        request = QgsFeatureRequest()
        request.setFlags(QgsFeatureRequest.Flag.NoGeometry)
        request.setSubsetOfAttributes(
            ['poly_id', 'elevation'],
            minima_points_layer.fields(),
        )

        for feature in minima_points_layer.getFeatures(request):
            poly_id = feature['poly_id']
            elevation = feature['elevation']

            if poly_id is not None and elevation is not None:
                minima_by_poly_id[poly_id] = elevation

        unique_values = list(minima_by_poly_id)


        self.update_log(f'Initial pass found n={len(lips)}')
        feedback.setProgress(0)
        milestones = list(range(5, 101, 5))
        self.update_log(f"\n0% complete @ {datetime.now().strftime('%H:%M.%S')}")

        store = context.temporaryLayerStore()

        if store.mapLayer(minima_points_layer.id()) is None:
            store.addMapLayer(minima_points_layer)

        for i, value in enumerate(unique_values):
            self.update_log(f'..Selected poly_id: {value}')

            start_z = minima_by_poly_id[value]
            minima_points_layer.selectByExpression(f'"poly_id" = {value}')
            
            for feature in minima_points_layer.selectedFeatures():
                start_z = feature['elevation']

            intersect = processing.run("native:extractbylocation", {'INPUT': seeded_layer,
                                                       'PREDICATE': [1],
                                                       'INTERSECT': QgsProcessingFeatureSourceDefinition(
                                                           minima_points_layer.id(), selectedFeaturesOnly=True,
                                                           featureLimit=-1,
                                                           geometryCheck=QgsFeatureRequest.InvalidGeometryCheck.GeometryAbortOnInvalid),
                                                        'OUTPUT': 'TEMPORARY_OUTPUT'},
                                                        is_child_algorithm=True, context=context)
            intersected_layer = self._as_vector_layer(intersect['OUTPUT'])
            context.temporaryLayerStore().addMapLayer(intersected_layer)

            try:
                self.update_log(f'...Selected seeds: n={intersected_layer.featureCount()}')

                if intersected_layer.featureCount() == 1:
                    with edit(intersected_layer):
                        for f in intersected_layer.getFeatures():
                            if not self.allow_peaks and f['diff_maxElev'] > self.cInterval:
                                self.update_log(f"...1, {f['ID']}, {f['ELEV']}, Basin contans a peak")
                            elif f['Extent'] < self.minODarea or f['Depth'] < self.minODdepth - self.DEPTH_EPSILON:
                                self.update_log(f"...1, {f['ID']}, {f['ELEV']}, Basin too small/shallow for mapping")
                            else:
                                self.update_log(f"...1, {f['ID']}, OK - mini")
                                lips.append(f['ID'])

                elif intersected_layer.featureCount() > 1 and start_z is not None:
                    lip = self.tracker(intersected_layer, start_z)
                    if lip:
                        lips.extend(lip)

                    if feedback.isCanceled():
                        return {}

            finally:
                if store.mapLayer(intersected_layer.id()) is not None:
                    store.removeMapLayer(intersected_layer.id())
                intersected_layer = None

            percentage_complete = (100.0 * (i + 1) / len(unique_values))
            while len(milestones) > 0 and percentage_complete >= milestones[0]:
                self.update_log(f"\n{milestones[0]}% complete @  {datetime.now().strftime('%H:%M.%S')}")
                # remove that milestone from the list
                milestones = milestones[1:]
            feedback.setProgress(percentage_complete)
            if feedback.isCanceled():
                return {}

        self.update_log('..\n\n4. Drawing OD')
        self.update_log('Creating OD polygons.')

        context.temporaryLayerStore().addMapLayer(contour_layer)
        lips = [x for x in lips if x is not None]
        unique_lips = list(set(lips))  # remove duplicates for a unique list
        n_lips = len(unique_lips)

        

        if n_lips > 1:
            contour_layer.selectByExpression(f'ID in {tuple(unique_lips)}')
        elif n_lips == 1:
            contour_layer.selectByExpression(f'"ID" = {unique_lips[0]}')

        polygonise = processing.run("qgis:linestopolygons", {
            'INPUT': QgsProcessingFeatureSourceDefinition(contour_layer.id(), selectedFeaturesOnly=True,
                                                          featureLimit=-1,
                                                          geometryCheck=QgsFeatureRequest.InvalidGeometryCheck.GeometryAbortOnInvalid),
            'OUTPUT': 'TEMPORARY_OUTPUT'}, context=context)
        od_polygons_layer = polygonise['OUTPUT']

        processing.run("native:createspatialindex", {'INPUT': od_polygons_layer},
                       is_child_algorithm=True, context=context)
        num_of_features = od_polygons_layer.featureCount()
        self.update_log(f'Number of OD mapped. n = {num_of_features}')
        if len(self.lip_blacklist) > 0:
            blacklist_str = ', '.join(str(x) for x in self.lip_blacklist)
            # self.update_log(f'Blacklisted lips: {blacklist_str}')

        #processing.run("native:createspatialindex", {'INPUT': minima_points_layer}, is_child_algorithm=True,
        #               context=context)
        #processing.run("native:createspatialindex", {'INPUT': od_polygons_layer}, is_child_algorithm=True, context=context)
        join_min = processing.run("native:joinattributesbylocation", {'INPUT': minima_points_layer,
                                                                      'PREDICATE': [5], 'JOIN': od_polygons_layer,
                                                                      'JOIN_FIELDS': ['ID'], 'METHOD': 0,
                                                                      'DISCARD_NONMATCHING': True,
                                                                      'PREFIX': '', 'OUTPUT': 'TEMPORARY_OUTPUT'}, context=context)
        join_min_layer = join_min['OUTPUT']

        request = QgsFeatureRequest()
        clause1 = QgsFeatureRequest.OrderByClause('ID_2', ascending=True)
        clause2 = QgsFeatureRequest.OrderByClause('elevation', ascending=True)
        orderby = QgsFeatureRequest.OrderBy([clause1, clause2])
        request.setOrderBy(orderby).setFlags(QgsFeatureRequest.Flag.NoGeometry)
        request.setSubsetOfAttributes(['ID_2', 'elevation'], join_min_layer.fields())

        dfeats = []
        track_id = -1
        for f in join_min_layer.getFeatures(request):
            if f['ID_2'] == track_id:
                dfeats.append(f.id())
            track_id = f['ID_2']

        join_min_layer.dataProvider().deleteFeatures(dfeats)

        # 4. OD nesting
        # -> Use the nesting field and overlay relationships to classify nesting. Start from parent (1) to child (2,..)
        self.update_log('..\n\n5. OD nesting pass 1')
        self.update_log('Processing nesting of OD polygons.')

        od_polygons_layer.dataProvider().addAttributes([QgsField("Nesting", QMetaType.Type.Int)])
        od_polygons_layer.updateFields()

        self.nesting(od_polygons_layer)

        # Add nesting information to the minima
        points_join = processing.run("native:joinattributestable",
                       {'INPUT': join_min_layer, 'FIELD': 'ID_2',
                        'INPUT_2': od_polygons_layer, 'FIELD_2': 'ID',
        'FIELDS_TO_COPY': ['Depth', 'Nesting'], 'METHOD': 1, 'DISCARD_NONMATCHING': False,
        'PREFIX': '', 'OUTPUT': 'TEMPORARY_OUTPUT'})
        nested_points = points_join['OUTPUT']

        context.temporaryLayerStore().addMapLayer(nested_points)
        context.temporaryLayerStore().addMapLayer(od_polygons_layer)

        idx = od_polygons_layer.dataProvider().fieldNameIndex('Nesting')
        max_nest = od_polygons_layer.maximumValue(idx)

        processing.run("native:createspatialindex", {'INPUT': nested_points}, is_child_algorithm=True, context=context)

        # Trim mapped polygons to remove nested OD with only one child within
        for n in range(max_nest,1,-1):
            self.update_log(f'Nesting {n}')
            nested_points.selectByExpression(f'"Nesting" = {n}')
            od_polygons_layer.selectByExpression(f'"Nesting" = {n - 1}')
            count = processing.run("native:countpointsinpolygon", {'POLYGONS': QgsProcessingFeatureSourceDefinition(
                od_polygons_layer.id(), selectedFeaturesOnly=True, featureLimit=-1,
                geometryCheck=QgsFeatureRequest.InvalidGeometryCheck.GeometryAbortOnInvalid), 'POINTS': QgsProcessingFeatureSourceDefinition(
                nested_points.id(), selectedFeaturesOnly=True, featureLimit=-1, geometryCheck=QgsFeatureRequest.InvalidGeometryCheck.GeometryAbortOnInvalid),
                                                           'WEIGHT': '', 'CLASSFIELD': '', 'FIELD': 'NUMPOINTS',
                                                           'OUTPUT': 'TEMPORARY_OUTPUT'},
                                   context=context)
            counted = count['OUTPUT']
            counted.selectByExpression('"NUMPOINTS" = 1')
            if counted.selectedFeatureCount() > 0:
                centroids = []
                features = counted.selectedFeatures()
                for feat in features:
                    centroids.append(feat['id'])

                # self.update_log(f'{tuple(centroids)}')
                # delete the polygons within those selected and at the appropiate nesting
                if len(centroids) == 1:
                    od_polygons_layer.selectByExpression(
                        f'overlay_within(@layer, filter:="ID = {centroids[0]}") and Nesting = {n}')
                elif len(centroids) > 1:
                    od_polygons_layer.selectByExpression(
                        f'overlay_within(@layer, filter:=ID in {tuple(centroids)}) and Nesting = {n}'
                    )
                if nested_points.selectedFeatureCount() > 1:
                    with edit(od_polygons_layer):
                        od_polygons_layer.deleteSelectedFeatures()

        # delete minima from those nested OD deleted
        polygons = []
        features = od_polygons_layer.getFeatures()
        for feat in features:
            polygons.append(feat['ID'])

        join_min_layer.selectByExpression(f'ID_2 not in {tuple(polygons)}')
        if join_min_layer.selectedFeatureCount() > 1:
            with edit(join_min_layer):
                join_min_layer.deleteSelectedFeatures()
        
        num_of_features = join_min_layer.featureCount()
        self.update_log(f'Minima points within mapped OD. n = {num_of_features}')

        # reset Nesting values and reevaluate
        with edit(od_polygons_layer):
            for f in od_polygons_layer.getFeatures():
                context_exp.setFeature(f)
                od_polygons_layer.changeAttributeValue(f.id(), idx, NULL)

        self.nesting(od_polygons_layer)
        self.update_log('Completed nesting')
        self.export_layer(nested_points, 'ODminima')
        self.export_layer(od_polygons_layer, 'ODpolygons')

        num_of_features = od_polygons_layer.featureCount()
        self.update_log(f'Exported OD: n = {num_of_features}')

        if load_od:
            context.addLayerToLoadOnCompletion(f'{self.ODfilename}|layername=ODpolygons',
                                               context.LayerDetails('ODpolygons', project=context.project()))

        self.update_log(f"Script finished at {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
        return {}

    def postProcessAlgorithm(self, context, feedback):
        layer = QgsProcessingUtils.mapLayerFromString(f'{self.ODfilename}|layername=ODpolygons', context)
        # Use random colors to create categorized symbol for each group/category
        categories = []
        # get unique values
        fni = layer.fields().indexFromName('Nesting')
        unique_values = layer.uniqueValues(fni)

        for unique_value in unique_values:
            symbol = QgsSymbol.defaultSymbol(layer.geometryType())

            # create renderer object
            category = QgsRendererCategory(unique_value, symbol, str(unique_value))
            # entry for the list of category items
            categories.append(category)

        # create renderer object
        renderer = QgsCategorizedSymbolRenderer('Nesting', categories)
        renderer.setOrderBy(QgsFeatureRequest.OrderBy([QgsFeatureRequest.OrderByClause('Nesting', True)]))
        renderer.setOrderByEnabled(True)
        # assign the created renderer to the layer
        if renderer is not None:
            layer.setRenderer(renderer)

        layer.triggerRepaint()
        return {self.OUTPUT: f'{self.ODfilename}|layername=ODpolygons'}

