    def check_lip(self, f, last_f):
        if f is not None:
            if f['ID'] in self.lip_blacklist:
                self.update_log('...Lip already blacklisted')
            elif self.allow_peaks == 0 and f['diff_maxElev'] > self.cInterval:
                self.update_log('...Lip skipped - no peaks allowed')
                self.lip_blacklist.append(f['ID'])
            elif self.allow_peaks == 1 and f['diff_maxElev'] > 0 and (f['diff_maxElev'] - last_f['diff_maxElev']) > 100:
                self.update_log('...Lip skipped - diff>100')
                self.lip_blacklist.append(f['ID'])
            elif f['Extent'] >= self.minODarea and f['Depth'] >= self.minODdepth:
                self.update_log('...Lip ' + str(f['ID']) + ' ok and marked')
                self.tracked_lips.append(f['ID'])
            else:
                self.update_log('...Lip skipped - not ok')
                self.lip_blacklist.append(f['ID'])

    def tracker(self, intersected_layer, start_z):
        request = QgsFeatureRequest()
        clause1 = QgsFeatureRequest.OrderByClause('Depth', ascending=True) # or ELEV?
        orderby = QgsFeatureRequest.OrderBy([clause1])
        request.setOrderBy(orderby).setFlags(QgsFeatureRequest.NoGeometry)
        context_exp = QgsExpressionContext()
        context_exp.appendScopes(QgsExpressionContextUtils.globalProjectLayerScopes(intersected_layer))

        seeds = 1
        last_elev = -9999  # needed if only 1 intersect on first transect line in file
        cont = []  # contours which have already crossed
        self.tracked_lips = []
        counter = 0
        max_count = intersected_layer.featureCount()
        error = 0
        last_f_2 = None
        last_f = None
        check_f = None
        last_contour = 1

        for f in intersected_layer.getFeatures(request):
            context_exp.setFeature(f)
            counter += 1

            if start_z > f['ELEV']:
                self.update_log('...' + str(f['ID']) + ', ' + str(start_z) + '>' + str(f['ELEV']) +', Minima above contour')
                error += 1
            elif f['ID'] in cont:
                self.update_log('...' + str(counter) + '/' + str(max_count) + ', ' + str(f['ID']) + ', Recrossing contour')
            else:
                diff = (f['Boundary'] / last_contour) * 100  # percentage increase from last contour

                #if f['Seeds'] == 0:
                #    self.update_log('...' + str(f['ID']) + ', ' + str("%.1f" % diff)
                #                    + '/' + str(self.contour_change) + ', Entering a contour without seeds')
                #    error += 1  # entering a contour without seeds
                if counter > 1 and (f['ELEV'] - last_elev) != self.cInterval:  # perimeters can be longer on lower elevations!
                    self.update_log('...' + str(f['ID']) + ', ' + str("%.1f" % diff)
                                    + '/' + str(self.contour_change) + ', Left basin')
                    error += 1  # left basin into another OD (contour getting smaller/diff)
                elif f['ELEV'] < int(last_elev):
                    self.update_log('...' + str(f['ID']) + ', ' + str("%.1f" % diff)
                                    + '/' + str(self.contour_change) + ', Going downhill')
                    error += 1  # going downhill
                elif diff > self.flatbottom and counter == 2:  # on the second contour
                    self.update_log('...' + str(counter) + '/' + str(max_count) + ', ' + str(f['ID']) + ', ' + str("%.1f" % diff)
                                    + '/' + str(self.flatbottom) + ', Too big second jump')
                    error += 1  # initial contour change too large

                elif diff > self.contour_change and counter > 2:  # above the second contour
                    self.update_log('...' + str(counter) + '/' + str(max_count) + str(f['ID']) + ', ' + str("%.1f" % diff)
                                    + '/' + str(self.contour_change) + ', Too big a jump')
                    error += 1  # contour change too large

                elif f['Seeds'] > seeds and seeds <= 2:
                    if counter == 2:
                        self.update_log(
                            '...' + str(counter) + '/' + str(max_count) + ', ' + str(f['ID']) + ', ' + str(
                                "%.1f" % diff) + '/' + str(self.flatbottom) + ', Seeds increased')
                        self.update_log('...' + 'Checking lip ' + str(check_f['ID']))
                    else:
                        self.update_log(
                        '...' + str(counter) + '/' + str(max_count) + ', ' + str(f['ID']) + ', ' + str("%.1f" % diff)
                        + '/' + str(self.contour_change) + ', Seeds increased')
                    self.update_log('...' + 'Checking lip ' + str(check_f['ID']))
                    if last_f_2:
                        self.check_lip(check_f, last_f_2)
                    else:
                        self.check_lip(check_f,
                                       last_f)  # for when checking the first contour (diff_maxElev jump does not matter)
                    check_f = f
                    last_f_2 = last_f
                    last_f = f

                elif self.allow_peaks == 0 and f['diff_maxElev'] > self.cInterval:  # don't track as potential lip, but continue up
                    self.update_log(
                        '...' + str(counter) + '/' + str(max_count) + ', '
                        + str(f['ID']) + ', Basin contains a peak ' + str(f['diff_maxElev']) + 'm above the lip')
                elif self.allow_peaks == 1 and last_f:
                    if f['diff_maxElev'] > 0 and (f['diff_maxElev'] - last_f['diff_maxElev']) > 100:  # don't track as potential lip, but continue up
                        self.update_log(
                            '...' + str(counter) + '/' + str(max_count) + ', '
                            + str(f['ID']) + ', Basin contains a sudden peak ' + str(f['diff_maxElev']) + 'm above the lip')
                        #error += 1  # contour change too large
                        self.update_log('...' + 'Checking lip ' + str(check_f['ID']))
                        if last_f_2:
                            self.check_lip(check_f, last_f_2)
                        else:
                            self.check_lip(check_f, last_f)  # if on the second contour
                        last_f = f
                    else:
                        self.update_log(
                            '...' + str(counter) + '/' + str(max_count)
                            + ', ' + str(f['ID']) + ', ' + ("%.1f" % diff) + '/'
                            + str(self.contour_change) + ', OK')
                        check_f = f
                        last_f_2 = last_f
                        last_f = f
                else:
                    self.update_log(
                       '...' + str(counter) + '/' + str(max_count)
                       + ', ' + str(f['ID']) + ', ' + ("%.1f" % diff) + '/'
                       + str(self.contour_change) + ', OK')
                    check_f = f
                    last_f_2 = last_f
                    last_f = f


            if error > 0 or counter == max_count:
                if check_f:
                    self.update_log('...' + 'Checking lip ' + str(check_f['ID']))
                    if last_f_2:
                        self.check_lip(check_f, last_f_2)
                    else:
                        self.check_lip(check_f, last_f) # if on the second contour
                    return self.tracked_lips

            cont.append(f['ID'])
            last_contour = f['Boundary']
            last_elev = f['ELEV']
            seeds = f['Seeds']

    def nesting(self, od_polygons_layer):
        field_idx = od_polygons_layer.fields().indexOf('Nesting')
        for i in range(1, 1000):
            if i == 1:
                od_polygons_layer.selectByExpression('(overlay_contains(@layer) is True and overlay_within(@layer) is False) or overlay_disjoint(@layer)')

            elif i > 1:
                od_polygons_layer.selectByExpression('overlay_within(@layer) and Nesting is NULL and overlay_within(@layer, filter:= Nesting is NULL) IS False')

            od_polygon_count = od_polygons_layer.selectedFeatureCount()
            if od_polygon_count == 0:
                break
            else:
                self.update_log('Nesting level ' + str(i) + ': n = ' + str(od_polygon_count))
                context_exp = QgsExpressionContext()
                context_exp.appendScopes(QgsExpressionContextUtils.globalProjectLayerScopes(od_polygons_layer))

                with edit(od_polygons_layer):
                    for f in od_polygons_layer.getSelectedFeatures():
                        context_exp.setFeature(f)
                        od_polygons_layer.changeAttributeValue(f.id(), field_idx, i)

    def update_log(self, message):
        t1 = datetime.now()
        if not message.startswith('..'):  # don't publish tracker updates to GUI
            self.feedback.pushInfo('{}'.format(str(t1 - self.t0)[:-4]) + ' ' + message + '\n')
        if self.write_log:
            if message.startswith('..'):
                self.logger.info(message)
            else:
                self.logger.info('{}'.format(str(t1 - self.t0)[:-4]) + ' ' + message)

    def create_od_gpkg(self, layer, layer_name):
        if os.path.exists(self.ODfilename):
            os.remove(self.ODfilename)
        params = {'INPUT': layer,
                  'LAYER_NAME': layer_name,
                  'OUTPUT': self.ODfilename}
        processing.run("native:savefeatures", params, is_child_algorithm=True, context=self.context, feedback=self.feedback)
        self.update_log('Exported ' + str(layer_name) + ' layer to ' + self.ODfilename)
    
    def export_layer(self, layer, layer_name):
        params = {'INPUT': layer,
                  'OPTIONS': '-overwrite -nln ' + layer_name,
                  'OUTPUT': self.ODfilename}
        processing.run("gdal:convertformat", params, is_child_algorithm=True, context=self.context, feedback=self.feedback)
        self.update_log('Exported ' + str(layer_name) + ' layer to ' + self.ODfilename)

    def processAlgorithm(self, parameters, context, feedback):
        self.context = context
        self.feedback = feedback
        self.t0 = datetime.now()
        self.minODarea = self.parameterAsDouble(parameters, self.min_OD_area, context)
        self.minODdepth = self.parameterAsInt(parameters, self.min_OD_depth, context)
        self.maxODperim = self.parameterAsInt(parameters, self.max_OD_perim, context)
        self.cInterval = self.parameterAsInt(parameters, self.contour_interval, context)
        self.contour_change = self.parameterAsInt(parameters, self.contour_threshold, context)
        self.flatbottom = self.parameterAsInt(parameters, self.flat_bottom, context)
        load_od = self.parameterAsInt(parameters, self.loadOD, context)
        self.allow_peaks = self.parameterAsInt(parameters, self.peaks, context)
        self.write_log = self.parameterAsInt(parameters, self.writeLog, context)
        self.lip_blacklist = []  # lips which have failed criteria from other minima starting points

        dem = self.parameterAsRasterLayer(parameters, self.INPUT, context)
        uri_components = QgsProviderRegistry.instance().decodeUri(dem.dataProvider().name(), dem.publicSource())
        self.ODfilename = self.parameterAsFile(parameters, self.OUTPUT, context)

        if self.mask not in parameters or parameters[self.mask] is None:
            mask = None
        else:
            mask = self.parameterAsVectorLayer(parameters, self.mask, context)

        if self.old_contours not in parameters or parameters[self.old_contours] is None:
            old_contours = None
            contours_name = 'Empty'
        else:
            old_contours = self.parameterAsVectorLayer(parameters, self.old_contours, context)
            contours_name = old_contours.name()

        grid_res_x = dem.rasterUnitsPerPixelX()
        grid_res_y = dem.rasterUnitsPerPixelY()

        if self.write_log:
            self.logger = logging.getLogger(__name__)
            console_handler = logging.StreamHandler()
            log_filename = os.path.splitext(self.ODfilename)[0] + '_' + self.t0.strftime('%Y%m%d_%H%M%S') + '_log.txt'
            if os.path.exists(log_filename):
                os.remove(log_filename)
            file_handler = logging.FileHandler(log_filename, mode="a", encoding="utf-8")
            self.logger.addHandler(console_handler)
            self.logger.addHandler(file_handler)
            self.logger.setLevel("INFO")
            self.update_log('Script started at ' + self.t0.strftime('%Y-%m-%d %H:%M:%S')+'\n')
            self.update_log('\nInput DEM: ' + uri_components['path']+'\n'
                            'Grid resolution (X,Y): ' + str(grid_res_x) + ', ' + str(grid_res_y) + ' m\n'
                            'Contour Interval: ' + str(parameters[self.contour_interval]) + ' m\n'
                            'Contour Threshold: ' + str(parameters[self.contour_threshold]) + '\n'
                            'Minimum OD area: ' + str(parameters[self.min_OD_area]) + ' km2\n'
                            'Mask: ' + str(mask.name()) + '\n'
                            'Predefined contours: ' + str(contours_name) + '\n'
                            'Output GPKG: ' + self.ODfilename + '\n'
                            'Projection: ' + dem.crs().authid() + '\n')

        # create the countours
        self.update_log('..\n\n1. Preparing files for mapping ODs')

        if old_contours:
            self.update_log('Backing up original contours')
            old_contours.selectAll()
            orig_contour_layer = processing.run("native:saveselectedfeatures",
                                                {'INPUT': old_contours, 'OUTPUT': 'memory:'})['OUTPUT']
            self.create_od_gpkg(orig_contour_layer, 'contours_original')

        else:
            self.update_log('Creating contours')
            contouring = processing.run("gdal:contour", {'INPUT': dem, 'BAND': 1, 'INTERVAL': self.cInterval,
                                                         'FIELD_NAME': 'ELEV', 'CREATE_3D': False,
                                                         'IGNORE_NODATA': False, 'NODATA': None, 'OFFSET': 0,
                                                         'EXTRA': '', 'OUTPUT': 'TEMPORARY_OUTPUT'},
                                        is_child_algorithm=True, context=context, feedback=feedback)
            orig_contour_layer = contouring['OUTPUT']
            self.create_od_gpkg(orig_contour_layer, 'contours_original')

        all_contours_layer = QgsVectorLayer(self.ODfilename + '|layername=contours_original', 'Lines', 'ogr')
        all_contours_layer.selectAll()
        contour_layer = processing.run("native:saveselectedfeatures", 
                                       {'INPUT': all_contours_layer, 'OUTPUT': 'memory:'},
                                       context=context, feedback=feedback)['OUTPUT']
        all_contours_layer.removeSelection()

        self.update_log('Found contours. n = ' + str(contour_layer.featureCount()))

        processing.run("native:createspatialindex", {'INPUT': contour_layer}, is_child_algorithm=True, context=context)

        # Check for cancelation
        if feedback.isCanceled():
            return {}

        if mask:
            contour_layer.selectAll()
            processing.run("native:selectbylocation", {'INPUT': contour_layer, 'PREDICATE': [0, 6], 'INTERSECT': mask,
                                                       'METHOD': 3},
                           is_child_algorithm=True, context=context, feedback=feedback)

            if contour_layer.selectedFeatureCount() > 0:
                with edit(contour_layer):
                    contour_layer.deleteSelectedFeatures()
                num_of_features = contour_layer.featureCount()
                self.update_log('Removed contours beyond the mask. n = ' + str(num_of_features))
            else:
                self.update_log('No contours lie beyond the mask.')

        # select remove open polylines by selecting where end and start points don't match
        contour_layer.selectByExpression('is_closed(@geometry) = FALSE')

        with edit(contour_layer):
            contour_layer.deleteSelectedFeatures()

        self.update_log('Removed open contours. n = ' + str(contour_layer.featureCount()))

        if contour_layer.dataProvider().fieldNameIndex("Boundary") == -1:
            contour_layer.dataProvider().addAttributes([QgsField("Boundary", QVariant.Int)])
            contour_layer.dataProvider().addAttributes([QgsField("Extent", QVariant.Double, "double", 10, 3)])
            contour_layer.updateFields()

        context_exp = QgsExpressionContext()
        context_exp.appendScopes(QgsExpressionContextUtils.globalProjectLayerScopes(contour_layer))

        with edit(contour_layer):
            field_idx = contour_layer.fields().indexOf('Boundary')
            for f in contour_layer.getFeatures():
                context_exp.setFeature(f)
                length = f.geometry().length()
                if length < (grid_res_x * 8) or length > self.maxODperim:# or length < self.minODperim:
                    contour_layer.deleteFeature(f.id())
                else:
                    contour_layer.changeAttributeValue(f.id(), field_idx, length)

        # Check for cancelation
        if feedback.isCanceled():
            return {}

        self.update_log('Removed small (' + str(grid_res_x * 8) + 'm) and big (' + str(self.maxODperim) + ' m) contours. n = ' +
                        str(contour_layer.featureCount()))

        # Check for cancelation
        if feedback.isCanceled():
            return {}

        # reduce allContours layer to use only those that could contain seeds (reduces number of intersections needed)
        self.update_log('Polygonising contours')
        polygonise = processing.run("qgis:linestopolygons", {'INPUT': contour_layer, 'OUTPUT': 'TEMPORARY_OUTPUT'})
        line2polygon_layer = polygonise['OUTPUT']

        with edit(line2polygon_layer):
            field_idx = line2polygon_layer.fields().indexOf('Extent')
            for f in line2polygon_layer.getFeatures():
                context_exp.setFeature(f)
                area = f.geometry().area() * 1E-6
                if area < self.minODarea:
                    line2polygon_layer.deleteFeature(f.id())
                else:
                    line2polygon_layer.changeAttributeValue(f.id(), field_idx, area)
        self.update_log('Removed small area contours. n = ' + str(line2polygon_layer.featureCount()))

        processing.run("native:createspatialindex", {'INPUT': line2polygon_layer},
                       is_child_algorithm=True, context=context)

        # remove contours with peaks inside or where too small to be considered OD
        self.update_log('Calculating contour depth stats')
        zonal = processing.run("native:zonalstatisticsfb", {'INPUT': line2polygon_layer, 'INPUT_RASTER': dem,
                                                            'RASTER_BAND': 1, 'COLUMN_PREFIX': '_', 'STATISTICS': [2, 3, 5, 6],
                                                            'OUTPUT': 'TEMPORARY_OUTPUT'},
                               context=context, feedback=feedback)
        allcontour_polygons_layer = zonal['OUTPUT']

        allcontour_polygons_layer.dataProvider().addAttributes([QgsField("diff_maxElev", QVariant.Int)])
        allcontour_polygons_layer.dataProvider().addAttributes([QgsField("Depth", QVariant.Int)])
        allcontour_polygons_layer.updateFields()
        max_diff_idx = allcontour_polygons_layer.fields().indexOf('diff_maxElev')
        depth_idx = allcontour_polygons_layer.fields().indexOf('Depth')
        expression = QgsExpression('"_max" - "ELEV"')
        expression_depth = QgsExpression('"ELEV" - "_min"')
        request = QgsFeatureRequest()
        request.setFlags(QgsFeatureRequest.NoGeometry)
        request.setSubsetOfAttributes(['_max', '_min', 'ELEV', 'Depth', 'diff_maxElev'], allcontour_polygons_layer.fields())
        context_exp = QgsExpressionContext()
        context_exp.appendScopes(QgsExpressionContextUtils.globalProjectLayerScopes(allcontour_polygons_layer))
        
        with edit(allcontour_polygons_layer):
            for f in allcontour_polygons_layer.getFeatures(request):
                context_exp.setFeature(f)
                allcontour_polygons_layer.changeAttributeValue(f.id(), max_diff_idx, expression.evaluate(context_exp))
                allcontour_polygons_layer.changeAttributeValue(f.id(), depth_idx, expression_depth.evaluate(context_exp))

        # spatial summary works more efficiently with contour count reduced as much as possible
        QgsProject.instance().addMapLayer(allcontour_polygons_layer, False)
        processing.run("native:createspatialindex", {'INPUT': allcontour_polygons_layer}, is_child_algorithm=True,
                       context=context)

        self.update_log('Selecting hills, shallow basins, and basins containing peaks')
        # delete isolated polygons that are too shallow. Quicker to do overlay query on subset (adds 40 mins to BedMachineV5)
        allcontour_polygons_layer.selectByExpression('"Depth" < 1')

        #
        if allcontour_polygons_layer.selectedFeatureCount() > 0:
            with edit(allcontour_polygons_layer):
                allcontour_polygons_layer.deleteSelectedFeatures()
        self.update_log('Removed shallow basins. n = ' + str(allcontour_polygons_layer.featureCount()))

        # delete polygons with a min greater than the lip (hills) or large peaks
        allcontour_polygons_layer.selectByExpression('"_min" > "ELEV" or "_median" > "ELEV" or "_mean" > "ELEV"')
        if allcontour_polygons_layer.selectedFeatureCount() > 0:
            with edit(allcontour_polygons_layer):
                allcontour_polygons_layer.deleteSelectedFeatures()
            self.update_log('Removed contours of mostly hills. n = ' + str(allcontour_polygons_layer.featureCount()))

        # delete lone polygons with a max elevation greater than the lip. The rest are dealt with in the tracker as some 'peaks' might be contained by higher lips.
        if self.allow_peaks == 0:
            allcontour_polygons_layer.selectByExpression(
                '"diff_maxElev" > '+str(self.cInterval) + ' and overlay_disjoint(@layer)')

            if allcontour_polygons_layer.selectedFeatureCount() > 0:
                with edit(allcontour_polygons_layer):
                    allcontour_polygons_layer.deleteSelectedFeatures()
            self.update_log('Removed contours containing peaks. n = ' + str(allcontour_polygons_layer.featureCount()))

        # create seeds
        processing.run("native:createspatialindex", {'INPUT': allcontour_polygons_layer}, is_child_algorithm=True, context=context)
        allcontour_polygons_layer.selectByExpression('overlay_contains(@layer)')
        allcontour_polygons_layer.invertSelection()

        self.update_log('Seed polygons. n = ' + str(allcontour_polygons_layer.selectedFeatureCount()))

        contour_polygons_layer = processing.run("native:saveselectedfeatures",
                                                {'INPUT': allcontour_polygons_layer, 'OUTPUT': 'memory:'})['OUTPUT']
        self.export_layer(contour_polygons_layer, 'seed_polygons')

        # 1. Find the OD minima
        # -> Identify the elevation minimum within the polygon. Create points, attach elevation and
        # remove those that don't match minima

        self.update_log('..\n\n2. Seeding basins')
        self.update_log('Creating OD minima points from '+str(contour_polygons_layer.featureCount())+' seed polygons')

        dem2point = processing.run("native:generatepointspixelcentroidsinsidepolygons",
                                   {'INPUT_RASTER': dem, 'INPUT_VECTOR': contour_polygons_layer,
                                    'OUTPUT': 'TEMPORARY_OUTPUT'}, feedback=feedback)
        minima_points_layer = dem2point['OUTPUT']

        processing.run("native:createspatialindex", {'INPUT': minima_points_layer}, is_child_algorithm=True,context=context)
        self.update_log('Created minima points. n = ' + str(minima_points_layer.featureCount()))

        if minima_points_layer.dataProvider().fieldNameIndex("elevation") == -1:
            minima_points_layer.dataProvider().addAttributes([QgsField("elevation", QVariant.Int)])
            minima_points_layer.updateFields()
        expression = QgsExpression('raster_value(\'' + dem.name() + '\',1,@geometry)')

        self.update_log('Extracting elevation data to OD minima points')

        context_exp = QgsExpressionContext()
        context_exp.appendScopes(QgsExpressionContextUtils.globalProjectLayerScopes(minima_points_layer))

        with edit(minima_points_layer):
            field_idx = minima_points_layer.fields().indexOf('elevation')
            for f in minima_points_layer.getFeatures():
                context_exp.setFeature(f)
                minima_points_layer.changeAttributeValue(f.id(), field_idx, expression.evaluate(context_exp))

        # Find single minima by deleting all but the lowest point for each poly
        self.update_log('Finding individual OD minima')
        request = QgsFeatureRequest()
        clause1 = QgsFeatureRequest.OrderByClause('poly_id', ascending=True)
        clause2 = QgsFeatureRequest.OrderByClause('elevation', ascending=True)
        orderby = QgsFeatureRequest.OrderBy([clause1, clause2])
        request.setOrderBy(orderby).setFlags(QgsFeatureRequest.NoGeometry)

        if minima_points_layer.featureCount() > 0:
            with edit(minima_points_layer):
                min_d = -9999
                min_id = -1
                for f in minima_points_layer.getFeatures(request):
                    if f['elevation'] is None:
                        continue
                    elif f['poly_id'] > min_id:
                        min_d = f['elevation']
                        min_id = f['poly_id']
                    elif f['elevation'] >= min_d:
                            minima_points_layer.deleteFeature(f.id())

        # Remove minima that are above their seed polygon
        join = processing.run("native:joinattributesbylocation", {'INPUT': minima_points_layer, 'PREDICATE': [0],
                                                                  'JOIN': contour_polygons_layer, 'JOIN_FIELDS': [],
                                                                  'METHOD': 0, 'DISCARD_NONMATCHING': False,
                                                                  'PREFIX': '',
                                                                  'OUTPUT': 'TEMPORARY_OUTPUT'},
                              context=context, feedback=feedback)
        joined_layer = join['OUTPUT']
        QgsProject.instance().addMapLayer(joined_layer, False)

        joined_layer.selectByExpression('"Elevation" > "ELEV"')
        processing.run("native:selectbylocation", {'INPUT': minima_points_layer,
                                                   'PREDICATE': [0],
                                                   'INTERSECT': QgsProcessingFeatureSourceDefinition(
                                                       joined_layer.id(), selectedFeaturesOnly=True, featureLimit=-1,
                                                       geometryCheck=QgsFeatureRequest.GeometryAbortOnInvalid),
                                                   'METHOD': 0},
                       is_child_algorithm=True, context=context, feedback=feedback)

        with edit(minima_points_layer):
            minima_points_layer.deleteSelectedFeatures()

        QgsProject.instance().removeMapLayer(joined_layer.id())
        num_of_features = minima_points_layer.featureCount()
        self.update_log('Reduced minima points. n = ' + str(num_of_features))

        if num_of_features <= 0:
            return {}

        # Add field for checking if OD seeds start to be contained by the same contour. Need to use minima points
        self.update_log('Aggregating seed count within contour polygons.')

        allcontour_polygons_layer.removeSelection()
        contour_polygons_layer.removeSelection()

        seeds = processing.run("native:countpointsinpolygon", {'POLYGONS': allcontour_polygons_layer,
                                                               'POINTS': minima_points_layer, 'WEIGHT': '',
                                                               'CLASSFIELD': '', 'FIELD': 'Seeds',
                                                               'OUTPUT': 'TEMPORARY_OUTPUT'},
                               context=context, feedback=feedback)
        seeds_layer = seeds['OUTPUT']
        processing.run("native:createspatialindex", {'INPUT': seeds_layer}, is_child_algorithm=True, context=context)

        within = processing.run("native:joinattributesbylocation", {'INPUT': seeds_layer, 'PREDICATE': [1],
                                                                    'JOIN': minima_points_layer,
                                                                    'JOIN_FIELDS': ['poly_id'], 'METHOD': 1,
                                                                    'DISCARD_NONMATCHING': True,
                                                                    'PREFIX': '', 'OUTPUT': 'TEMPORARY_OUTPUT'},
                                context=context, feedback=feedback)
        seeded_layer = within['OUTPUT']

        # remove contours that are not necessary
        seeded_layer.selectByExpression('Seeds = 0')
        self.update_log('Selecting unseeded . n = ' + str(seeded_layer.selectedFeatureCount()))
        with edit(seeded_layer):
            seeded_layer.deleteSelectedFeatures()

        poly2line = processing.run("native:polygonstolines", {'INPUT': seeded_layer, 'OUTPUT': 'TEMPORARY_OUTPUT'},
                                   context=context, feedback=feedback)
        contour_layer = poly2line['OUTPUT']

        with edit(contour_layer):
            my_field = contour_layer.fields().indexFromName('fid')
            contour_layer.dataProvider().deleteAttributes([my_field])
        contour_layer.updateFields()

        with edit(seeded_layer):
            my_field = seeded_layer.fields().indexFromName('fid')
            seeded_layer.dataProvider().deleteAttributes([my_field])
        seeded_layer.updateFields()

        self.export_layer(contour_layer, 'tracking_contours')

        # 2. Setup contour tracking
        self.update_log('..\n\n3. Tracking')
        processing.run("native:createspatialindex", {'INPUT': seeded_layer}, is_child_algorithm=True, context=context)
        processing.run("native:createspatialindex", {'INPUT': minima_points_layer}, is_child_algorithm=True, context=context)

        QgsProject.instance().addMapLayer(contour_layer, False)
        QgsProject.instance().addMapLayer(minima_points_layer, False)

        self.update_log('Iterating over minima points n=' + str(num_of_features))
        if self.allow_peaks == 1:
            seeded_layer.selectByExpression('"Depth" >= ' + str(self.minODdepth) + ' and overlay_disjoint(@layer)')
        else:
            seeded_layer.selectByExpression('"Depth" >= ' + str(self.minODdepth) + ' and "diff_maxElev" <= '+str(self.cInterval) + ' and overlay_disjoint(@layer)')

        # create a first list of basins with a single contour
        lips = []
        features = seeded_layer.selectedFeatures()
        for feat in features:
            lips.append(feat['ID'])

        if len(lips) == 1:
            seeded_layer.selectByExpression('"ID" = '+str(lips[0]))
        elif len(lips) > 1:
            seeded_layer.selectByExpression("ID in {}".format(tuple(lips)))
        if seeded_layer.selectedFeatureCount() > 1:
            with edit(seeded_layer):
                seeded_layer.deleteSelectedFeatures()

        processing.run("native:selectbylocation", {'INPUT': minima_points_layer,
                                                   'PREDICATE': [6],
                                                   'INTERSECT': seeded_layer,
                                                   'METHOD': 0},
                       is_child_algorithm=True, context=context, feedback=feedback)
        idx = minima_points_layer.fields().indexOf("poly_id")
        unique_values = minima_points_layer.uniqueValues(idx)

        self.update_log('Initial pass found n=' + str(len(lips)))
        feedback.setProgress(0)
        milestones = list(range(5, 101, 5))
        self.update_log('\n{}% complete @ '.format('0') + datetime.now().strftime("%H:%M.%S"))

        for i, value in enumerate(unique_values):
            self.update_log('..Selected poly_id: ' + str(value))
            minima_points_layer.selectByExpression('"poly_id" = ' + str(value))
            start_z = None
            for feature in minima_points_layer.selectedFeatures():
                start_z = feature['elevation']

            intersect = processing.run("native:extractbylocation", {'INPUT': seeded_layer,
                                                       'PREDICATE': [1],
                                                       'INTERSECT': QgsProcessingFeatureSourceDefinition(
                                                           minima_points_layer.id(), selectedFeaturesOnly=True,
                                                           featureLimit=-1,
                                                           geometryCheck=QgsFeatureRequest.GeometryAbortOnInvalid),
                                                        'OUTPUT': 'TEMPORARY_OUTPUT'})
            intersected_layer = intersect['OUTPUT']

            self.update_log('...Selected seeds: n=' + str(intersected_layer.featureCount()))
            if intersected_layer.featureCount() == 1:
                with edit(intersected_layer):
                    for f in intersected_layer.getFeatures():
                        if self.allow_peaks == 0 and f['diff_maxElev'] > self.cInterval:
                            self.update_log('...' + str(1) + ', ' + str(f['ID']) + ', ' + str(f['ELEV']) + ', ' + str(
                                'Basin contans a peak'))
                        elif f['Extent'] < self.minODarea or f['Depth'] < + self.minODdepth:
                            self.update_log('...' + str(1) + ', ' + str(f['ID']) + ', ' + str(f['ELEV']) + ', ' + str(
                                'Basin too small/shallow for mapping'))
                        else:
                            self.update_log('...' + str(1) + ', ' + str(f['ID']) + ', OK - mini')
                            lips.append(f['ID'])

            elif intersected_layer.featureCount() > 1 and start_z is not None:
                lip = self.tracker(intersected_layer, start_z)
                if lip:
                    lips.extend(lip)

                if feedback.isCanceled():
                    return {}

            percentage_complete = (100.0 * (i + 1) / len(unique_values))
            while len(milestones) > 0 and percentage_complete >= milestones[0]:
                self.update_log('\n{}% complete @ '.format(milestones[0]) + ' ' + datetime.now().strftime("%H:%M.%S"))
                # remove that milestone from the list
                milestones = milestones[1:]
            feedback.setProgress(percentage_complete)
            if feedback.isCanceled():
                return {}

        self.update_log('..\n\n4. Drawing OD')
        self.update_log('Creating OD polygons.')

        lips = [x for x in lips if x is not None]
        unique_lips = list(set(lips))  # remove duplicates for a unique list
        n_lips = len(unique_lips)

        if n_lips > 1:
            contour_layer.selectByExpression("ID in {}".format(tuple(unique_lips)))
        elif n_lips == 1:
            contour_layer.selectByExpression('"ID" = '+str(unique_lips[0]))
        polygonise = processing.run("qgis:linestopolygons", {
            'INPUT': QgsProcessingFeatureSourceDefinition(contour_layer.id(), selectedFeaturesOnly=True,
                                                          featureLimit=-1,
                                                          geometryCheck=QgsFeatureRequest.GeometryAbortOnInvalid),
            'OUTPUT': 'TEMPORARY_OUTPUT'}, context=context, feedback=feedback)
        od_polygons_layer = polygonise['OUTPUT']

        QgsProject.instance().removeMapLayer(contour_layer.id())

        processing.run("native:createspatialindex", {'INPUT': od_polygons_layer},
                       is_child_algorithm=True, context=context)
        num_of_features = od_polygons_layer.featureCount()
        self.update_log('Number of OD mapped. n = ' + str(num_of_features))
        if len(self.lip_blacklist) > 0:
            self.update_log('Blacklisted lips: ' + ', '.join(str(x) for x in self.lip_blacklist))

        processing.run("native:createspatialindex", {'INPUT': minima_points_layer}, is_child_algorithm=True,
                       context=context)
        processing.run("native:createspatialindex", {'INPUT': od_polygons_layer}, is_child_algorithm=True, context=context)
        join_min = processing.run("native:joinattributesbylocation", {'INPUT': minima_points_layer,
                                                                      'PREDICATE': [5], 'JOIN': od_polygons_layer,
                                                                      'JOIN_FIELDS': ['ID'], 'METHOD': 0,
                                                                      'DISCARD_NONMATCHING': True,
                                                                      'PREFIX': '', 'OUTPUT': 'TEMPORARY_OUTPUT'},
                                  context=context, feedback=feedback)
        join_min_layer = join_min['OUTPUT']

        request = QgsFeatureRequest()
        clause1 = QgsFeatureRequest.OrderByClause('ID_2', ascending=True)
        clause2 = QgsFeatureRequest.OrderByClause('elevation', ascending=True)
        orderby = QgsFeatureRequest.OrderBy([clause1, clause2])
        request.setOrderBy(orderby).setFlags(QgsFeatureRequest.NoGeometry)
        request.setSubsetOfAttributes(['ID_2', 'elevation'], join_min_layer.fields())

        dfeats = []
        track_id = -1
        for f in join_min_layer.getFeatures(request):
            if f['ID_2'] == track_id:
                dfeats.append(f.id())
            track_id = f['ID_2']

        join_min_layer.dataProvider().deleteFeatures(dfeats)

        # 4. OD nesting
        # -> Use the nesting field and overlay relationships to classify nesting. Start from parent (1) to child (2,..)
        self.update_log('..\n\n5. OD nesting pass 1')
        self.update_log('Processing nesting of OD polygons.')

        od_polygons_layer.dataProvider().addAttributes([QgsField("Nesting", QVariant.Int)])
        od_polygons_layer.updateFields()

        self.nesting(od_polygons_layer)

        # Add nesting information to the minima
        points_join = processing.run("native:joinattributestable",
                       {'INPUT': join_min_layer, 'FIELD': 'ID_2',
                        'INPUT_2': od_polygons_layer, 'FIELD_2': 'ID',
        'FIELDS_TO_COPY': ['Depth', 'Nesting'], 'METHOD': 1, 'DISCARD_NONMATCHING': False,
        'PREFIX': '', 'OUTPUT': 'TEMPORARY_OUTPUT'})
        nested_points = points_join['OUTPUT']

        QgsProject.instance().addMapLayer(nested_points, False)
        QgsProject.instance().addMapLayer(od_polygons_layer, False)

        idx = od_polygons_layer.dataProvider().fieldNameIndex('Nesting')
        max_nest = od_polygons_layer.maximumValue(idx)

        # Trim mapped polygons to remove nested OD with only one child within
        for n in range(max_nest,1,-1):
            self.update_log('Nesting ' + str(n))
            nested_points.selectByExpression('"Nesting" = '+str(n))
            od_polygons_layer.selectByExpression('"Nesting" = '+str(n-1))
            count = processing.run("native:countpointsinpolygon", {'POLYGONS': QgsProcessingFeatureSourceDefinition(
                od_polygons_layer.id(), selectedFeaturesOnly=True, featureLimit=-1,
                geometryCheck=QgsFeatureRequest.GeometryAbortOnInvalid), 'POINTS': QgsProcessingFeatureSourceDefinition(
                nested_points.id(), selectedFeaturesOnly=True, featureLimit=-1, geometryCheck=QgsFeatureRequest.GeometryAbortOnInvalid),
                                                           'WEIGHT': '', 'CLASSFIELD': '', 'FIELD': 'NUMPOINTS',
                                                           'OUTPUT': 'TEMPORARY_OUTPUT'})
            counted = count['OUTPUT']
            counted.selectByExpression('"NUMPOINTS" = 1')
            if counted.selectedFeatureCount() > 0:
                centroids = []
                features = counted.selectedFeatures()
                for feat in features:
                    centroids.append(feat['id'])

                self.update_log(format(tuple(centroids)))
                # delete the polygons within those selected and at the appropiate nesting
                if len(centroids) == 1:
                    od_polygons_layer.selectByExpression(
                        'overlay_within(@layer, filter:="ID = '+ str(centroids[0])+') and Nesting = '+str(n))
                elif len(centroids) > 1:
                    od_polygons_layer.selectByExpression('overlay_within(@layer, filter:='+"ID in {}".format(tuple(centroids))+') and Nesting = '+str(n))
                if nested_points.selectedFeatureCount() > 1:
                    with edit(od_polygons_layer):
                        od_polygons_layer.deleteSelectedFeatures()

        # delete minima from those nested OD deleted
        polygons = []
        features = od_polygons_layer.getFeatures()
        for feat in features:
            polygons.append(feat['ID'])

        join_min_layer.selectByExpression('ID_2 not in {}'.format(tuple(polygons)))
        if join_min_layer.selectedFeatureCount() > 1:
            with edit(join_min_layer):
                join_min_layer.deleteSelectedFeatures()
        
        num_of_features = join_min_layer.featureCount()
        self.update_log('Minima points within mapped OD. n = ' + str(num_of_features))

        # reset Nesting values and reevaluate
        with edit(od_polygons_layer):
            for f in od_polygons_layer.getFeatures():
                context_exp.setFeature(f)
                od_polygons_layer.changeAttributeValue(f.id(), idx, NULL)

        self.nesting(od_polygons_layer)
        self.update_log('Completed nesting')
        self.export_layer(nested_points, 'ODminima')
        self.export_layer(od_polygons_layer, 'ODpolygons')

        num_of_features = od_polygons_layer.featureCount()
        self.update_log('Exported OD: n = ' + str(num_of_features))

        if load_od == 1:
            context.addLayerToLoadOnCompletion(self.ODfilename + '|layername=ODpolygons',
                                               context.LayerDetails('ODpolygons', project=context.project()))

        self.update_log('Script finished at ' + datetime.now().strftime('%Y-%m-%d %H:%M:%S') + '\n')
        return {}

    def postProcessAlgorithm(self, context, feedback):
        layer = QgsProcessingUtils.mapLayerFromString(self.ODfilename + '|layername=ODpolygons', context)
        # Use random colors to create categorized symbol for each group/category
        categories = []
        # get unique values
        fni = layer.fields().indexFromName('Nesting')
        unique_values = layer.uniqueValues(fni)

        for unique_value in unique_values:
            symbol = QgsSymbol.defaultSymbol(layer.geometryType())

            # create renderer object
            category = QgsRendererCategory(unique_value, symbol, str(unique_value))
            # entry for the list of category items
            categories.append(category)

        # create renderer object
        renderer = QgsCategorizedSymbolRenderer('Nesting', categories)
        renderer.setOrderBy(QgsFeatureRequest.OrderBy([QgsFeatureRequest.OrderByClause('Nesting', True)]))
        renderer.setOrderByEnabled(True)
        # assign the created renderer to the layer
        if renderer is not None:
            layer.setRenderer(renderer)

        layer.triggerRepaint()
        return {self.OUTPUT: self.ODfilename + '|layername=ODpolygons'}

    def name(self):
        """
        Returns the algorithm name, used for identifying the algorithm. This
        string should be fixed for the algorithm, and must not be localised.
        The name should be unique within each provider. Names should contain
        lowercase alphanumeric characters only and no spaces or other
        formatting characters.
        """
        return 'Map closed basins'

    def displayName(self):
        """
        Returns the translated algorithm name, which should be used for any
        user-visible display of the algorithm name.
        """
        return self.tr(self.name())

    def tr(self, string):
        return QCoreApplication.translate('Processing', string)

    def shortHelpString(self):
        file = os.path.dirname(__file__) + '/doc/mapper.help'
        if not os.path.exists(file):
            return ''
        with open(file) as helpf:
            help = helpf.read()
        return help

    def flags(self):
        """
        Algorithm manipulating project (toggle layer) or using external library are not thread safe
        See :https://api.qgis.org/api/classQgsProcessingAlgorithm.html#a6a8c21fab75e03f50f45e41a9d67dbc3a229dea6cedf8c59132196dee09d4f2f6
        """
        return super().flags() | QgsProcessingAlgorithm.FlagNoThreading

    def createInstance(self):
        return ODmapperAlgorithm()
