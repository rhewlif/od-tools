    def update_log(self, message):
        t1 = datetime.now()
        if not message.startswith('..'):  # don't publish tracker updates to GUI
            self.feedback.pushInfo('{}'.format(str(t1 - self.t0)[:-4]) + ': ' + message + '\n')
        if self.keep_log:
            if message.startswith('..'):
                self.logger.info(message)
            else:
                self.logger.info('{}'.format(str(t1 - self.t0)[:-4]) + ': ' + message)

    def _as_vector_layer(self, output, context):
        """
        Resolve a Processing output into a QgsVectorLayer.

        Processing algorithms may return either a layer object or a temporary
        output/source string, depending on QGIS version and provider.
        """
        if isinstance(output, QgsVectorLayer):
            return output

        layer = QgsProcessingUtils.mapLayerFromString(output, context)

        if layer is None:
            raise QgsProcessingException(
                f'Could not resolve Processing output layer: {output!r}'
            )

        if not isinstance(layer, QgsVectorLayer):
            raise QgsProcessingException(
                f'Processing output is not a vector layer: {output!r}'
                f'got {type(layer).__name__}'
            )

        return layer

    def renesting(self, od_polygons_layer):
        field_idx = od_polygons_layer.fields().indexOf('Class_Nesting')
        for i in range(1, 1000):
            if i == 1:
                od_polygons_layer.selectByExpression('(overlay_contains(@layer) is True and overlay_within(@layer) is False) or overlay_disjoint(@layer)')

            elif i > 1:
                od_polygons_layer.selectByExpression('overlay_within(@layer) and Class_Nesting is NULL and overlay_within(@layer, filter:= Class_Nesting is NULL) IS False')

            od_polygon_count = od_polygons_layer.selectedFeatureCount()
            if od_polygon_count == 0:
                break
            else:
                self.update_log('Nesting level ' + str(i) + ': n = ' + str(od_polygon_count))
                context_exp = QgsExpressionContext()
                context_exp.appendScopes(QgsExpressionContextUtils.globalProjectLayerScopes(od_polygons_layer))

                with edit(od_polygons_layer):
                    for f in od_polygons_layer.getSelectedFeatures():
                        context_exp.setFeature(f)
                        od_polygons_layer.changeAttributeValue(f.id(), field_idx, i)

    def processAlgorithm(self, parameters, context, feedback):
        self.context = context
        self.feedback = feedback
        self.t0 = datetime.now()

        self.od = self.parameterAsVectorLayer(parameters, self.INPUT, context)
        self.id_field = self.parameterAsString(parameters, self.ID_COL, context)
        self.elev_field = self.parameterAsString(parameters, self.ELEV_COL, context)
        self.nesting_field = self.parameterAsString(parameters, self.NESTING_COL, context)
        self.elong_threshold = self.parameterAsDouble(parameters, self.ELONGATION_THRESHOLD, context)
        self.round_threshold = self.parameterAsDouble(parameters, self.ROUNDNESS_THRESHOLD, context)   
        self.out_path = self.parameterAsOutputLayer(parameters, self.OUTPUT, context)
        self.keep_log = self.parameterAsBool(parameters, self.WRITE_LOG, context)
        self.logger = logging.getLogger(f'{__name__}.{id(self)}')
        self.logger.setLevel(logging.INFO)
        self.logger.propagate = False

        if self.od.crs().isGeographic():
            raise QgsProcessingException(
                'Input basin polygons use a geographic CRS. '
                'Use a projected CRS with metre-based map units before calculating '
                'areas or volumes.'
            )

        output_file = self.out_path.split('|', 1)[0]

        if not output_file.lower().endswith('.gpkg'):
            raise QgsProcessingException(
                'Output must be a GeoPackage file with a ".gpkg" extension.'
            )
        
        if self.keep_log:
            log_filename = os.path.splitext(self.out_path)[0] + '_' + self.t0.strftime('%Y%m%d_%H%M%S') + '_log.txt'
            if os.path.exists(log_filename):
                os.remove(log_filename)
            file_handler = logging.FileHandler(log_filename, mode="a", encoding="utf-8")
            self.logger.addHandler(file_handler)
            
        self.update_log('Script started at ' + self.t0.strftime('%Y-%m-%d %H:%M:%S') + '\n')

        if self.DEM in parameters and parameters[self.DEM] is not None:
            self.dem_file = self.parameterAsRasterLayer(parameters, self.DEM, context)
            dem_path = self.dem_file.publicSource()
        else:
            dem_path = 'No DEM provided - volume calcs skipped'
        uri_components_od = QgsProviderRegistry.instance().decodeUri(self.od.dataProvider().name(), self.od.publicSource())
        
        if self.VALLEY_FILE in parameters and parameters[self.VALLEY_FILE] is not None:
            self.valley_points = self.parameterAsVectorLayer(parameters, self.VALLEY_FILE, context)
            valley_path = self.valley_points.publicSource()
        else:
            valley_path = 'No valleys provided - valley classification skipped'

        if self.ISOCHRONE_FILE in parameters and parameters[self.ISOCHRONE_FILE] is not None:
            self.isochrone_polys = self.parameterAsVectorLayer(parameters, self.ISOCHRONE_FILE, context)
            isochrones_path = self.isochrone_polys.publicSource()
        else:
            isochrones_path = 'No isochrones provided - age classification skipped'
        if self.THERMAL_FILE in parameters and parameters[self.THERMAL_FILE] is not None:
            self.thermal_state = self.parameterAsVectorLayer(parameters, self.THERMAL_FILE, context)
            thermal_path = self.thermal_state.publicSource()
        else:
            thermal_path = 'No thermal state provided - thermal classification skipped'
        
        self.update_log('\n\nInput polygons: ' + uri_components_od['path'] +
                        '\n\nElongation threshold: ' + str(self.elong_threshold) +
                        '\n\nRoundness threshold: ' + str(self.round_threshold) +
                        '\n\nInput DEM: ' + dem_path +
                        '\n\nInput Valleys: ' + valley_path +
                        '\n\nInput Isochrones: ' + isochrones_path +
                        '\n\nThermal State: ' + thermal_path +
                        '\n\nOutput GPKG: ' + self.out_path)

        output_file = self.out_path.split('|', 1)[0]

        if os.path.exists(output_file):
            os.remove(output_file)
        
        ### calculate volumes ###    
        if self.dem_file:
            self.update_log('Calculating volumes...')

            feature_count = self.od.featureCount()

            if feature_count == 0:
                raise QgsProcessingException('The input basin layer contains no features.')

            seen_ids = set()

            for feature in self.od.getFeatures():
                basin_id = feature[self.id_field]

                if basin_id is None or basin_id == NULL:
                    raise QgsProcessingException(
                        f'Feature {feature.id()} has a null value in "{self.id_field}".'
                    )

                if basin_id in seen_ids:
                    raise QgsProcessingException(
                        f'The selected ID field "{self.id_field}" is not unique. '
                        f'Duplicate value: {basin_id!r}'
                    )

                seen_ids.add(basin_id)

            feedback.setProgress(0)
            milestones = list(range(5, 101, 5))
            self.update_log(
                f'\n0% complete @ {datetime.now().strftime("%H:%M.%S")}'
            )

            # Requires that self.id_field contains unique, non-null values.
            volumes_by_id = {}

            for i, feature in enumerate(self.od.getFeatures()):
                if feedback.isCanceled():
                    return {}
                basin_id = feature[self.id_field]
                elevation = feature[self.elev_field]

                if basin_id is None or basin_id == NULL:
                    raise QgsProcessingException(
                        f'Feature {feature.id()} has a null basin ID.'
                    )

                if elevation is None or elevation == NULL:
                    self.update_log(
                        f'..Skipping basin {basin_id}: elevation is null.'
                    )
                    volumes_by_id[basin_id] = None
                    percentage_complete = 100.0 * (i + 1) / feature_count
                    feedback.setProgress(int(percentage_complete))
                    continue

                # Creates a temporary layer containing only this basin.
                # $id refers to QGIS's internal feature ID, not your selected ID field.
                basin_result = processing.run(
                    "native:extractbyexpression",
                    {
                        "INPUT": self.od,
                        "EXPRESSION": f"$id = {feature.id()}",
                        "OUTPUT": "TEMPORARY_OUTPUT",
                    },
                    is_child_algorithm=True,
                    context=context
                )

                basin_mask = self._as_vector_layer(basin_result["OUTPUT"], context)

                clip_result = processing.run(
                    "gdal:cliprasterbymasklayer",
                    {
                        "INPUT": self.dem_file.source(),
                        "MASK": basin_mask,
                        "SOURCE_CRS": None,
                        "TARGET_CRS": None,
                        "TARGET_EXTENT": None,
                        "NODATA": None,
                        "ALPHA_BAND": False,
                        "CROP_TO_CUTLINE": True,
                        "KEEP_RESOLUTION": False,
                        "SET_RESOLUTION": False,
                        "X_RESOLUTION": None,
                        "Y_RESOLUTION": None,
                        "MULTITHREADING": False,
                        "OPTIONS": "",
                        "DATA_TYPE": 0,
                        "EXTRA": "",
                        "OUTPUT": "TEMPORARY_OUTPUT",
                    },
                    is_child_algorithm=True,
                    context=context
                )

                volume_result = processing.run(
                    "native:rastersurfacevolume",
                    {
                        "INPUT": clip_result["OUTPUT"],
                        "BAND": 1,
                        "LEVEL": elevation,
                        "METHOD": 1,
                        "OUTPUT_HTML_FILE": "TEMPORARY_OUTPUT",
                    },
                    is_child_algorithm=True,
                    context=context
                )

                raw_volume = volume_result.get("VOLUME")

                if raw_volume is None:
                    self.update_log(
                        f'..No volume returned for basin {basin_id}.'
                    )
                    volume_km3 = None
                else:
                    # Retain the negative sign only if it is scientifically intended:
                    # QGIS result is assumed m³, converted here to km³.
                    volume_km3 = -float(raw_volume) * 1e-9

                volumes_by_id[basin_id] = volume_km3

                self.update_log(
                    f'..ID: {basin_id}, Elev: {elevation}, '
                    f'Vol: {volume_km3:.4f} km³'
                    if volume_km3 is not None
                    else f'..ID: {basin_id}, Elev: {elevation}, Vol: NULL'
                )

                percentage_complete = 100.0 * (i + 1) / feature_count

                while milestones and percentage_complete >= milestones[0]:
                    milestone = milestones.pop(0)
                    self.update_log(
                        f'\n{milestone}% complete @ '
                        f'{datetime.now().strftime("%H:%M.%S")}'
                    )

                feedback.setProgress(int(percentage_complete))


        ### calculate shape attributes ###
        self.update_log('Calculating shape attributes...')
        box_result = processing.run("qgis:minimumboundinggeometry", {
            'INPUT': self.od, 'FIELD': self.id_field, 'TYPE': 1, 'OUTPUT': 'TEMPORARY_OUTPUT'},
            is_child_algorithm=True,
            context=context, feedback=feedback)
        boxed = self._as_vector_layer(box_result['OUTPUT'], context)

        join_result = processing.run("native:joinattributestable", {
            'INPUT': self.od, 'FIELD': self.id_field, 'INPUT_2': boxed, 'FIELD_2': self.id_field,
            'FIELDS_TO_COPY': [], 'METHOD': 1, 'DISCARD_NONMATCHING': False, 'PREFIX': '',
            'OUTPUT': 'TEMPORARY_OUTPUT'},
            is_child_algorithm=True,
            context=context,
            feedback=feedback)
        od = self._as_vector_layer(join_result['OUTPUT'], context)


        self.update_log('Calculating roundness/elongation...')

        od.dataProvider().addAttributes([QgsField("Roundness", QMetaType.Type.Double, "double", 10, 3),
                                         QgsField("Elong_mbg", QMetaType.Type.Double, "double", 10, 3),
                                         QgsField("Type", QMetaType.Type.QString)])
        od.updateFields()

        circularity_idx = od.fields().indexOf('Roundness')
        type_idx = od.fields().indexOf('Type')
        elong_idx = od.fields().indexOf('Elong_mbg')
        expression_circularity = QgsExpression('round(roundness(@geometry),3)')
        expression_elong = QgsExpression(
            'CASE '
            'WHEN "width" IS NULL OR "width" = 0 OR "height" IS NULL THEN NULL '
            'ELSE "height" / "width" '
            'END'
        )
        #expression_circularity = QgsExpression('4 * pi() * area(@geometry) / perimeter(@geometry) ^ 2') # actual calc of roundness()
        request = QgsFeatureRequest()
        request.setSubsetOfAttributes(['length', 'width', 'Roundness', 'area', 'type'], od.fields())

        expr_context = QgsExpressionContext()
        expr_context.appendScopes(QgsExpressionContextUtils.globalProjectLayerScopes(od))

        if 'Area_km2' not in [fld.name() for fld in od.fields()]:
            od.dataProvider().addAttributes([QgsField("Area_km2", QMetaType.Type.Double, "double", 10, 3)])
            od.updateFields()
            area_idx = od.fields().indexOf('Area_km2')
            expression_area = QgsExpression('area(@geometry)*1E-6')
            expr_context.appendScopes(QgsExpressionContextUtils.globalProjectLayerScopes(od))
            with edit(od):
                for f in od.getFeatures():
                    expr_context.setFeature(f)
                    # planimetric area - suitable for small-scale features
                    od.changeAttributeValue(f.id(), area_idx, expression_area.evaluate(expr_context))

        with edit(od):
            for f in od.getFeatures(request):
                if feedback.isCanceled():
                    return {}
                
                expr_context.setFeature(f)
                area_km2 = f['Area_km2']

                circ = expression_circularity.evaluate(expr_context)
                od.changeAttributeValue(f.id(), circularity_idx, circ)
                elong = expression_elong.evaluate(expr_context)
                od.changeAttributeValue(f.id(), elong_idx, elong)

                if area_km2 is None or area_km2 == NULL:
                    od_type = NULL
                elif area_km2 == 0:
                    od_type = 'empty'
                elif circ is None or circ == NULL or elong is None or elong == NULL:
                    od_type = NULL
                elif elong < 1.8 and circ >= self.round_threshold:
                    od_type = 'circular'
                elif elong >= self.elong_threshold or circ < 0.3:
                    od_type = 'elongated'
                else:
                    od_type = NULL

                od.changeAttributeValue(f.id(), type_idx, od_type)
                circ_text = f'{circ:.3f}' if circ is not None else 'NULL'
                type_text = str(od_type) if od_type is not None else 'NULL'
                self.update_log('..ID: ' + str(f[self.id_field]) + ', Roundness: ' + circ_text + ', Type: ' + type_text)

        

        if self.dem_file:
            if 'Volume_km3' not in [fld.name() for fld in od.fields()]:
                od.dataProvider().addAttributes([QgsField("Volume_km3", QMetaType.Type.Double, "double", 10, 4)])
                od.updateFields()

            vol_idx = od.fields().indexOf('Volume_km3')
            with edit(od):
                for feature in od.getFeatures():
                    basin_id = feature[self.id_field]
                    od.changeAttributeValue(
                        feature.id(),
                        vol_idx,
                        volumes_by_id.get(basin_id)
                    )

            nest_idx = od.fields().indexFromName(self.nesting_field)
            max_nest = od.maximumValue(nest_idx)

            for n in range(1, max_nest + 1):
                od.selectByExpression(self.nesting_field + ' = ' + str(n))
                total_sum = od.aggregate(QgsAggregateCalculator.Aggregate.Sum, "Volume_km3", fids=od.selectedFeatureIds())
                self.update_log('Total OD volumes (nesting='+str(n)+'): ' + str(round(total_sum[0], 2)) + ' km^3')


        #### classify valleys ####
        if self.valley_points:
            self.update_log('Classifying valleys')
            processing.run("native:createspatialindex", {'INPUT': self.valley_points}, is_child_algorithm=True, context=context)

            fluvial_result = processing.run(
                "native:extractbyexpression",
                {
                    "INPUT": self.valley_points,
                    "EXPRESSION": (
                        '"Class" = \'Fluvial\' AND '
                        '"Classification score" < 0.5'
                    ),
                    "OUTPUT": "TEMPORARY_OUTPUT",
                },
                is_child_algorithm=True,
                context=context,
                feedback=feedback
            )

            fluvial_points = self._as_vector_layer(fluvial_result["OUTPUT"], context)
            processing.run("native:createspatialindex", {'INPUT': fluvial_points}, is_child_algorithm=True, context=context)

            fluvial_count_result = processing.run(
                "native:countpointsinpolygon",
                {
                    "POLYGONS": od,
                    "POINTS": fluvial_points,
                    "FIELD": "Fluvial",
                    "OUTPUT": "TEMPORARY_OUTPUT",
                },
                is_child_algorithm=True,
                context=context,
                feedback=feedback,
            )

            od = self._as_vector_layer(fluvial_count_result["OUTPUT"], context)

            glacial_result = processing.run(
                "native:extractbyexpression",
                {
                    "INPUT": self.valley_points,
                    "EXPRESSION": (
                        '"Class" = \'Glacial\' AND '
                        '"Classification score" >= 0.5'
                    ),
                    "OUTPUT": "TEMPORARY_OUTPUT",
                },
                is_child_algorithm=True,
                context=context,
                feedback=feedback,
            )

            glacial_points = self._as_vector_layer(glacial_result["OUTPUT"], context)
            processing.run("native:createspatialindex", {'INPUT': glacial_points}, is_child_algorithm=True, context=context)

            glacial_count_result = processing.run(
                "native:countpointsinpolygon",
                {
                    "POLYGONS": od,
                    "POINTS": glacial_points,
                    "FIELD": "Glacial",
                    "OUTPUT": "TEMPORARY_OUTPUT",
                },
                is_child_algorithm=True,
                context=context,
                feedback=feedback,
            )

            od = self._as_vector_layer(glacial_count_result["OUTPUT"], context)

            if "Valley_type" not in od.fields().names():
                od.dataProvider().addAttributes([
                    QgsField("Valley_type", QMetaType.Type.QString, "string", 20)
                ])
                od.updateFields()

            fluvial_idx = od.fields().indexOf("Fluvial")
            glacial_idx = od.fields().indexOf("Glacial")
            valley_type_idx = od.fields().indexOf("Valley_type")

            with edit(od):
                for feature in od.getFeatures():
                    if feedback.isCanceled():
                        return {}
                    fluvial = feature[fluvial_idx] or 0
                    glacial = feature[glacial_idx] or 0

                    if glacial > fluvial and fluvial == 0:
                        valley_type = "Glacial_HC"
                    elif glacial > fluvial:
                        valley_type = "Glacial_LC"
                    elif fluvial > glacial and glacial == 0:
                        valley_type = "Fluvial_HC"
                    elif fluvial > glacial:
                        valley_type = "Fluvial_LC"
                    elif fluvial == glacial and fluvial > 0:
                        valley_type = "Mixed"
                    else:
                        valley_type = NULL

                    od.changeAttributeValue(feature.id(), valley_type_idx, valley_type)

        if self.isochrone_polys:
            self.update_log('Extracting last occupation age...')

            age_field = 'age'
            output_age_field = 'last_occupied'
            intersect_age_field = 'iso_age'

            if age_field not in self.isochrone_polys.fields().names():
                raise QgsProcessingException(
                    f'Isochrone layer does not contain the required "{age_field}" field.'
                )

            # Add the destination field only if it does not already exist.
            if output_age_field not in od.fields().names():
                od.dataProvider().addAttributes([
                    QgsField(
                        output_age_field,
                        QMetaType.Type.Double,
                        'double',
                        8,
                        1,
                    )
                ])
                od.updateFields()

            last_occupied_idx = od.fields().indexOf(output_age_field)


            # Ensure the input layers use the same CRS before comparing geometries.
            if od.crs() != self.isochrone_polys.crs():
                raise QgsProcessingException(
                    'The basin and isochrone layers must use the same CRS for '
                    'last-occupation age classification.'
                )

            age_field = 'age'

            if age_field not in self.isochrone_polys.fields().names():
                raise QgsProcessingException(
                    f'Isochrone layer is missing required field "{age_field}".'
                )

            self.update_log('Building isochrone spatial index...')

            isochrone_index = QgsSpatialIndex()
            isochrones_by_fid = {}

            iso_request = QgsFeatureRequest()
            iso_request.setFilterRect(od.extent())

            for isochrone in self.isochrone_polys.getFeatures(iso_request):
                if feedback.isCanceled():
                    return {}

                age = isochrone[age_field]
                geometry = isochrone.geometry()

                if age is None or age == NULL:
                    continue

                if geometry is None or geometry.isEmpty():
                    continue

                try:
                    age = float(age)
                except (TypeError, ValueError):
                    raise QgsProcessingException(
                        f'Invalid age value {age!r} in isochrone feature '
                        f'{isochrone.id()}.'
                    )

                isochrone_index.addFeature(isochrone)
                isochrones_by_fid[isochrone.id()] = {
                    'age': age,
                    'geometry': geometry,
                }

            self.update_log(
                f'Finding intersecting isochrones for {od.featureCount()} basins...'
            )

            # Basin ID -> most recent isochrone age.
            # For ka before present, the smallest numeric age is the youngest.
            last_age_by_id = {}
            basin_count = od.featureCount()

            for i, basin in enumerate(od.getFeatures()):
                if feedback.isCanceled():
                    return {}

                basin_id = basin[self.id_field]
                basin_geometry = basin.geometry()

                if basin_id is None or basin_id == NULL:
                    continue

                if basin_geometry is None or basin_geometry.isEmpty():
                    continue

                # Fast bounding-box lookup.
                candidate_fids = isochrone_index.intersects(
                    basin_geometry.boundingBox()
                )

                # Sort candidates from youngest to oldest.
                #
                # This assumes lower age = more recent, e.g. ka before present.
                candidate_fids.sort(
                    key=lambda fid: isochrones_by_fid[fid]['age']
                )

                # Prepare the basin geometry once. This speeds up repeated spatial tests
                # against potentially many candidate isochrones.
                basin_engine = QgsGeometry.createGeometryEngine(
                    basin_geometry.constGet()
                )
                basin_engine.prepareGeometry()

                youngest_age = None

                for isochrone_fid in candidate_fids:
                    isochrone_data = isochrones_by_fid[isochrone_fid]
                    isochrone_geometry = isochrone_data['geometry']

                    # The candidates are ordered youngest first. Therefore the first
                    # actual intersection is the required last-occupation age.
                    if basin_engine.intersects(isochrone_geometry.constGet()):
                        youngest_age = isochrone_data['age']
                        break

                if youngest_age is not None:
                    last_age_by_id[basin_id] = youngest_age

                # Do not update the GUI for every feature unnecessarily.
                if basin_count and (i % 10 == 0 or i == basin_count - 1):
                    feedback.setProgress(int(100.0 * (i + 1) / basin_count))

            # Write the aggregated value back to every basin.
            with edit(od):
                for feature in od.getFeatures():
                    if feedback.isCanceled():
                        return {}

                    basin_id = feature[self.id_field]

                    od.changeAttributeValue(
                        feature.id(),
                        last_occupied_idx,
                        last_age_by_id.get(basin_id, NULL),
                    )

            self.update_log(
                f'Assigned last-occupation ages to '
                f'{len(last_age_by_id)} of {od.featureCount()} basins.'
            )


        ### classify thermal state
        if self.thermal_state:
            self.update_log('Classifying by thermal state...')

            intersect_result = processing.run("native:multiintersection", {
                'INPUT': od,
                'OVERLAYS': [self.thermal_state],
                'OVERLAY_FIELDS_PREFIX': 'ts_', 'OUTPUT': 'TEMPORARY_OUTPUT'},
                is_child_algorithm=True,
                context=context,
                feedback=feedback,)
            intersected = self._as_vector_layer(intersect_result['OUTPUT'], context)    

            # create a dictionary of necessary fields
            area_by_basin_state = defaultdict(float)
            subglacial_area_by_basin = defaultdict(float)

            for feature in intersected.getFeatures():
                basin_id = feature[self.id_field]
                thermal_state = feature['ts_thermal_state']

                if basin_id is None or thermal_state is None:
                    continue

                area_km2 = feature.geometry().area() * 1e-6

                # Total area of this particular thermal state in the basin.
                area_by_basin_state[(basin_id, thermal_state)] += area_km2

                # Total area intersecting any thermal-state polygon.
                subglacial_area_by_basin[basin_id] += area_km2

            state_to_field = {
                -1: 'ts_cold',
                0: 'ts_uncertain',
                1: 'ts_warm',
            }

            thermal_output_fields = [
                QgsField('subglacial_area', QMetaType.Type.Double, 'double', 12, 3),
                QgsField('ts_warm', QMetaType.Type.Double, 'double', 10, 3),
                QgsField('ts_cold', QMetaType.Type.Double, 'double', 10, 3),
                QgsField('ts_uncertain', QMetaType.Type.Double, 'double', 10, 3),
            ]

            existing = set(od.fields().names())
            fields_to_add = [
                field for field in thermal_output_fields
                if field.name() not in existing
            ]

            if fields_to_add:
                od.dataProvider().addAttributes(fields_to_add)
                od.updateFields()

            cold_idx = od.fields().indexOf('ts_cold')
            uncertain_idx = od.fields().indexOf('ts_uncertain')
            warm_idx = od.fields().indexOf('ts_warm')
            subglacial_idx = od.fields().indexOf('subglacial_area')

            state_to_index = {
                -1: cold_idx,
                0: uncertain_idx,
                1: warm_idx,
            }

            with edit(od):
                for feature in od.getFeatures():
                    basin_id = feature[self.id_field]

                    total_area = subglacial_area_by_basin.get(basin_id, 0.0)

                    od.changeAttributeValue(
                        feature.id(),
                        subglacial_idx,
                        round(total_area, 3)
                    )

                    for thermal_state, field_idx in state_to_index.items():
                        state_area = area_by_basin_state.get(
                            (basin_id, thermal_state),
                            0.0
                        )

                        percent = (
                            100.0 * state_area / total_area
                            if total_area > 0
                            else 0.0
                        )

                        od.changeAttributeValue(
                            feature.id(),
                            field_idx,
                            round(percent, 3)
                        )

            if feedback.isCanceled():
                return {}

        od.dataProvider().addAttributes([QgsField("Class_Nesting", QMetaType.Type.Int)])
        od.updateFields()
        if od.featureCount() > 0:
            self.renesting(od)

        save_result = processing.run("native:savefeatures", {'INPUT': od,
                  'LAYER_NAME': 'glacial_od_class',
                  'OUTPUT': self.out_path}, is_child_algorithm=True, context=context, feedback=feedback)
        self.output_destination = save_result['OUTPUT']
        # Rename the layer QGIS already queued (honours the "open output file" checkbox)
        if context.willLoadLayerOnCompletion(self.out_path):
            details = context.layerToLoadOnCompletionDetails(self.out_path)
            details.name = 'Glacial OD class'
            context.addLayerToLoadOnCompletion(self.out_path, details)

        self.update_log('Exported ' + str(od) + ' layer to ' + self.output_destination)
        self.update_log('Script finished at ' + datetime.now().strftime('%Y-%m-%d %H:%M:%S') + '\n')

        return {self.OUTPUT: self.output_destination}

    def postProcessAlgorithm(self, context, feedback):
        style_path = os.path.join(os.path.dirname(__file__), 'styles', 'od_type.qml')
        # Style the exact layer QGIS will load: look it up using the queued key, not a rebuilt path
        source = self.out_path if context.willLoadLayerOnCompletion(self.out_path) else self.output_destination
        layer = QgsProcessingUtils.mapLayerFromString(source, context)

        if layer is None:
            feedback.reportError(
                'Output layer was not available for styling. '
                f'Destination: {self.output_destination}'
            )
        elif not os.path.exists(style_path):
            feedback.reportError(f'Output style file does not exist: {style_path}')
        else:
            error_message, success = layer.loadNamedStyle(style_path)
            if success:
                layer.triggerRepaint()
            else:
                feedback.reportError(f'Could not load output style: {error_message}')

        return {self.OUTPUT: self.output_destination}

