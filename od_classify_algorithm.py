class ClassifyAlgorithm(QgsProcessingAlgorithm):
    post_processors = {}
    OUTPUT = 'OUTPUT'
    DEM = 'DEM'
    INPUT = 'INPUT'
    elev_field = 'elev_field'
    nesting_field = 'nesting_field'
    valleys = 'valleys'
    isochrones = 'isochrones'
    thermal = 'thermal'
    id_field = 'id_field'
    writeLog = 'writeLog'

    def __init__(self):
        super().__init__()
        self.logger = None
        self.feedback = None
        self.context = None
        self.t0 = None
        self.logger = None
        self.write_log = None
        self.dem_file = None
        self.valley_points = None
        self.isochrone_polys = None
        self.thermal_state = None

